  stop(paste0(
    "  [nooutlier] This keyword is not supported and filters ",
    "anything. It thresholded |spvar| on the Gelman-normalized scale, which has ",
    "no fixed meaning now that normalization happens in R after subsetting. ",
    "Model name requested: '", model_name, "'. ",
    "Use 'iqr' instead, or regenerate the job file with generate_hpc_jobs.py."))
}

# spvar and the mediator arrive as their {x}_normalized names, but those columns
# do not exist yet (normalization is below), so resolve to the raw columns.  The
# 1.5xIQR fence is quantile-based, so it selects exactly the same rows on either
# scale.
#
# BOTH fences are computed on `df` as it stands here — AFTER spusers and
# nopsychosis, and BEFORE either fence is applied.  Two things follow, and both
# are deliberate:
#
#   1. An "outlier" is defined relative to the sample being analysed, matching
#      nonsp_predictors.R and the normalization that runs below.
#   2. The mediator's quartiles describe the frame that ENTERS this step, not
#      whatever the spvar fence happened to leave behind.  Computing them after
#      the spvar drop would make the mediator's fence depend on the exposure's
#      tail, so the same mediator value could be kept or dropped depending on
#      which exposure it was paired with.  The two fences are independent by
#      construction; only their row-dropping composes.
#
# The drops are then applied in order (spvar, then mediator) purely so the log
# reports how many rows each one removed.  Order does not affect the result: the
# retained set is the intersection of two fixed intervals.
if (grepl("iqr", model_name, ignore.case = FALSE)) {
  n_before_iqr <- nrow(df)

  ## iqr_fence(): the 1.5xIQR interval for one column, or NULL if it is all NA.
  iqr_fence <- function(x, label) {
    if (all(is.na(x))) {
      message(paste0("  [iqr] All values missing for ", label, "; no fence computed."))
      return(NULL)
    }
    q1      <- as.numeric(stats::quantile(x, probs = 0.25, na.rm = TRUE))
    q3      <- as.numeric(stats::quantile(x, probs = 0.75, na.rm = TRUE))
    iqr_val <- q3 - q1
    list(q1 = q1, q3 = q3, iqr = iqr_val,
         lower = q1 - 1.5 * iqr_val, upper = q3 + 1.5 * iqr_val)
  }

  ## apply_iqr_fence(): drop rows outside a precomputed fence, and log the drop.
  ## Rows missing the column are dropped too, matching the previous behaviour.
  apply_iqr_fence <- function(df, col, fence, role) {
    if (is.null(fence)) return(df)
    n_before <- nrow(df)
    df <- df[!is.na(df[[col]]) &
             df[[col]] >= fence$lower &
             df[[col]] <= fence$upper, ]
    message(paste0("  [iqr] ", role, " fence (", col,
                   ", Q1=", round(fence$q1, 4), ", Q3=", round(fence$q3, 4),
                   ", IQR=", round(fence$iqr, 4),
                   ", bounds=[", round(fence$lower, 4), ", ", round(fence$upper, 4), "]): ",
                   nrow(df), " rows (removed ", n_before - nrow(df), ")"))
    df
  }

  spvar_iqr_col    <- resolve_raw_column(df, spvar)
  mediator_iqr_col <- resolve_raw_column(df, mediator)

  ## Both computed here, on the same frame, before either is applied.
  spvar_fence    <- iqr_fence(df[[spvar_iqr_col]],    paste0("spvar=", spvar_iqr_col))
  mediator_fence <- iqr_fence(df[[mediator_iqr_col]], paste0("mediator=", mediator_iqr_col))

  df <- apply_iqr_fence(df, spvar_iqr_col,    spvar_fence,    "spvar")
  df <- apply_iqr_fence(df, mediator_iqr_col, mediator_fence, "mediator")

  message(paste0("  [iqr] IQR exclusion total: ", nrow(df),
                 " rows (removed ", n_before_iqr - nrow(df), ")"))
}

