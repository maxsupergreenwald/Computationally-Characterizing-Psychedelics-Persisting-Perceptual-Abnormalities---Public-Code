################################################################################
# hpc_mediation.R — Bayesian Bivariate Mediation Model for HPC
################################################################################
# One job = one mediation model:  spvar → mediator → dv
#
# Calls process_and_save_mediation_model() from helper_scripts/ to produce all
# standard outputs, making results directly compatible with the local
# 04_visualizations/ pipeline.
#
# The input CSV is RAW (changed 2026-08-22).  This script applies its row filters,
# drops rows incomplete on any model term, and only THEN Gelman-normalizes, via
# gelman_normalization.R.  Predictors and the mediator are therefore centred and
# scaled on exactly the rows that enter the likelihood.  Previously the CSV
# arrived pre-normalized from generate_hpc_jobs.py, which meant every subsetted
# model was scaled to a larger sample than it was fitted on.
#
# Arguments (generated by 03_hpc/generate_hpc_jobs.py):
#   [1]  spvar           SP predictor column name (raw in CSV; normalized here)
#   [2]  mediator        Mediator column name as model RESPONSE (raw in CSV)
#   [3]  mediator_name_in_outcome_model  Mediator column name as predictor in DV formula
#                        (usually same as mediator; differs for vch_bl_yes_0 etc.)
#   [4]  dv              DV column name (NOT normalized)
#   [5]  covs_str        Covariate formula RHS, e.g. "age_v2 + sex_v2 + raven_total"
#                        Use "" for UNIVARIATE (no covariates)
#   [6]  mediator_family brms family for mediator model:
#                        student_t | gaussian | beta | zero_inflated_beta | gamma | lognormal
#   [7]  dv_family       brms family for DV model:
#                        zero_negbinomial | bernoulli | student_t | gaussian | cumulative
#   [8]  model_name      Canonical model name (used for directory and file naming)
#   [9]  df_path         Absolute path to the RAW master CSV
#  [10]  results_dir     Base output directory → saves to {results_dir}/{model_name}/
#  [11]  helpers_dir     Absolute path to helper_scripts/ directory
#  [12]  iter            MCMC iterations (default: 8000)
#  [13]  warmup          MCMC warmup iterations (default: 6000)
################################################################################

