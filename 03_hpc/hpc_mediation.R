# --------------------------------------------------------------------------
# Ordered factor conversion for monotonic (mo()) covariates.
#
# Mirrors nonsp_predictors.R exactly, including the message text, so the two
# execution scripts prepare a mo() covariate identically.  `monotonic_covariate_vars`
# is sourced from the auto-generated monotonic_covariates_vars.R in the "Load data"
# block above (gelman_normalize_df() needs it to exclude these from normalization).
# Edit MONOTONIC_COVARIATES in modules/master_config.py, not this list.
#
# WHY THIS EXISTS (added 2026-09-03).  brms accepts a bare numeric in mo() and
# will fit it monotonically without warning, so its absence was silent.  For a
# covariate coded as CONSECUTIVE integers with EVERY level present in the analysis
# sample the two encodings are exactly equivalent -- make_standata() gives
# byte-identical Xmo / Jmo / con_simo -- which is why the 12 previously fitted
# empirical_covariates_spusers mediation models were numerically correct.
#
# They diverge as soon as a level is absent.  brms's numeric path uses
# x - min(x) with Jmo = max(x) - min(x), which KEEPS an empty interior level;
# as.ordered(as.integer(x)) applied here, AFTER row filtering and complete-case
# deletion, DROPS it and renumbers.  A row filter that empties one education
# level would therefore have made this script and nonsp_predictors.R fit two
# different monotonic specifications for the same covariate, with no error from
# either.  Converting here closes that gap.
# --------------------------------------------------------------------------

for (v in monotonic_covariate_vars) {
  if (v %in% names(df)) {
    df[[v]] <- as.ordered(as.integer(df[[v]]))
    message(paste0(
      "  [ordinal prep] ", v, " -> ordered factor, levels: ",
      paste(levels(df[[v]]), collapse = ", ")
    ))
  }
}

