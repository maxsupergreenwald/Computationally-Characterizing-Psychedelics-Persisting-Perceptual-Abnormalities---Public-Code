# --------------------------------------------------------------------------
# Extract path coefficients (A, B, C') with 94% HDI and pd
# --------------------------------------------------------------------------
# Saves posterior summaries for individual path coefficients on the
# link/latent scale (NOT response scale — use mc_mediation_summary.csv for
# response-scale causal effects).
#
# Naming (brms convention):
#   A path  (spvar → mediator) : b_{mediator_name_in_brms}_{spvar}
#   B path  (mediator → dv mu) : b_{dv_brms}_{mediator_name_in_outcome_model}
#   C' path (spvar → dv mu)    : b_{dv_brms}_{spvar}
# For hurdle_negbinom_huvary, hu-submodel paths are also included:
#   B_hu  (mediator → dv hu)   : b_hu_{dv_brms}_{mediator_name_in_outcome_model}
#   C'_hu (spvar → dv hu)      : b_hu_{dv_brms}_{spvar}
#
# All estimates are on the link scale (log for count submodels, logit for
# hurdle/bernoulli). Reported point estimate = posterior MEAN; the posterior
# median is stored alongside it in the `median` column but is not reported.
#
# Saved to: {results_dir}/{model_name}/path_coefficients_summary.csv
# Columns: path, var_brms_col, median, mean, hdi_lower_94, hdi_upper_94,
#          prob_above_0, prob_below_0, p_direction, n_draws
# --------------------------------------------------------------------------
message("Extracting path coefficients (A, B, C') with 94% HDI...")
tryCatch({
  d_paths  <- as_draws_df(fit)
  mediator_name_in_brms <- resp_brms[[mediator]]      # brms-internal mediator response name
  dv_brms  <- resp_brms[[dv]]            # brms-internal DV response name
  # spvar and mediator_name_in_outcome_model used verbatim as predictor names (underscores preserved)

  # Helper: summarise one draw vector into a single-row data.frame
  path_summary <- function(coefficient_draws, path_label, col_name) {
    coefficient_draws <- as.numeric(coefficient_draws)

    ## 94% highest density interval — narrowest interval holding 94% of draws.
    hdi_bounds <- bayestestR::hdi(coefficient_draws, ci = 0.94)

    ## Direction probabilities; p_direction is the larger of the two.
    prob_above_zero <- mean(coefficient_draws > 0)
    prob_below_zero <- mean(coefficient_draws < 0)
    p_direction     <- max(prob_above_zero, prob_below_zero)

    data.frame(
      path         = path_label,
      var_brms_col = col_name,
      median       = median(coefficient_draws),
      mean         = mean(coefficient_draws),
      hdi_lower_94 = hdi_bounds$CI_low,
      hdi_upper_94 = hdi_bounds$CI_high,
      prob_above_0 = prob_above_zero,
      prob_below_0 = prob_below_zero,
      p_direction  = p_direction,
      n_draws      = length(coefficient_draws),
      stringsAsFactors = FALSE
    )
  }

  path_rows <- list()

  # A path: spvar → mediator (mediator submodel, log or logit link)
  col_a <- paste0("b_", mediator_name_in_brms, "_", spvar)
  if (col_a %in% names(d_paths)) {
    path_rows[["a"]] <- path_summary(d_paths[[col_a]], "a", col_a)
    message(sprintf("  A path (%s): median=%.4f pd=%.3f",
                    col_a, path_rows[["a"]]$median, path_rows[["a"]]$p_direction))
  } else {
    message("  WARNING: A-path column '", col_a, "' not found in draws.")
  }

  # B path (mu): mediator → DV mu submodel (log or identity link)
  col_b <- paste0("b_", dv_brms, "_", mediator_name_in_outcome_model)
  if (col_b %in% names(d_paths)) {
    path_rows[["b"]] <- path_summary(d_paths[[col_b]], "b", col_b)
    message(sprintf("  B path mu (%s): median=%.4f pd=%.3f",
                    col_b, path_rows[["b"]]$median, path_rows[["b"]]$p_direction))
  } else {
    message("  WARNING: B-path (mu) column '", col_b, "' not found in draws.")
  }

  # C' path (mu): spvar → DV mu submodel (direct effect, log or identity link)
  col_c <- paste0("b_", dv_brms, "_", spvar)
  if (col_c %in% names(d_paths)) {
    path_rows[["c_prime"]] <- path_summary(d_paths[[col_c]], "c_prime", col_c)
    message(sprintf("  C' path mu (%s): median=%.4f pd=%.3f",
                    col_c, path_rows[["c_prime"]]$median, path_rows[["c_prime"]]$p_direction))
  } else {
    message("  WARNING: C'-path (mu) column '", col_c, "' not found in draws.")
  }

  # Hu-submodel paths (hurdle_negbinom_huvary only; logit link)
  if (dv_hu_zi_varying) {
    col_b_hu <- paste0("b_hu_", dv_brms, "_", mediator_name_in_outcome_model)
    if (col_b_hu %in% names(d_paths)) {
      path_rows[["b_hu"]] <- path_summary(d_paths[[col_b_hu]], "b_hu", col_b_hu)
      message(sprintf("  B path hu (%s): median=%.4f pd=%.3f",
                      col_b_hu, path_rows[["b_hu"]]$median, path_rows[["b_hu"]]$p_direction))
    } else {
      message("  WARNING: B-path (hu) column '", col_b_hu, "' not found in draws.")
    }

    col_c_hu <- paste0("b_hu_", dv_brms, "_", spvar)
    if (col_c_hu %in% names(d_paths)) {
      path_rows[["c_hu"]] <- path_summary(d_paths[[col_c_hu]], "c_hu", col_c_hu)
      message(sprintf("  C' path hu (%s): median=%.4f pd=%.3f",
                      col_c_hu, path_rows[["c_hu"]]$median, path_rows[["c_hu"]]$p_direction))
    } else {
      message("  WARNING: C'-path (hu) column '", col_c_hu, "' not found in draws.")
    }
  }

  if (length(path_rows) > 0) {
    paths_df  <- do.call(rbind, path_rows)
    paths_dir <- file.path(results_dir, model_name)
    dir.create(paths_dir, recursive = TRUE, showWarnings = FALSE)
    if (convergence_gate$pass) {
      paths_csv <- file.path(paths_dir, "path_coefficients_summary.csv")
      write.csv(paths_df, paths_csv, row.names = FALSE)
    } else {
      message("[convergence gate] WITHHELD: ", file.path(paths_dir, "path_coefficients_summary.csv"))
    }
    message("Saved: ", paths_csv)
  } else {
    message("WARNING: No path rows extracted — path_coefficients_summary.csv not written.")
  }

}, error = function(e) {
  message("Path coefficient extraction failed: ", e$message)
})

# --------------------------------------------------------------------------
# Extract hu-submodel path coefficients (b and c' on the hu/logit scale)
# --------------------------------------------------------------------------
# When dv_hu_zi_varying=TRUE, the fit contains b_hu_{dv_brms}_{spvar_brms}
# and b_hu_{dv_brms}_{mediator_name_in_outcome_model_brms} coefficients. These capture how
# the predictor and mediator affect the *probability of any nonzero response*
# (the hurdle submodel), supplementing the count-submodel (mu) paths reported
# by process_and_save_mediation_model().
#
# Saved to: {results_dir}/{model_name}/hu_paths_summary.csv
# Columns: path, var_brms_col, median, mean, hdi_lower_94, hdi_upper_94,
#          prob_above_0, prob_below_0, p_direction, n_draws
#          `mean` is the reported estimate (POINT_ESTIMATE_COL in
#          modules/master_config.py); `median` is retained, not reported.
#
# Naming note — brms strips underscores from RESPONSE names only (in bivariate models).
# Predictor and covariate names keep their underscores verbatim.
#   dv_brms = resp_brms[[dv]]        — brms-internal response name
#   spvar                            — predictor, underscores PRESERVED
#   mediator_name_in_outcome_model                   — mediator as DV predictor, underscores PRESERVED
# Eg. b_hu_capsvision_avg_life_dose is the spvar → hu coefficient for avg_life_dose -> caps_vision
# --------------------------------------------------------------------------
if (dv_hu_zi_varying) {
  message("Extracting hu-submodel path coefficients...")
  tryCatch({
    d_hu    <- as_draws_df(fit)
    dv_brms <- resp_brms[[dv]]

    hu_rows <- list()

    # c'_hu: spvar → hu (direct effect on hurdle probability, logit scale)
    # brms column: b_hu_{dv_no_underscores}_{spvar_verbatim}
    col_c_hu <- paste0("b_hu_", dv_brms, "_", spvar)
    if (col_c_hu %in% names(d_hu)) {
      hu_path_draws <- as.numeric(d_hu[[col_c_hu]])

      ## 94% highest density interval, and the two direction probabilities.
      hdi_bounds      <- bayestestR::hdi(hu_path_draws, ci = 0.94)
      prob_above_zero <- mean(hu_path_draws > 0)
      prob_below_zero <- mean(hu_path_draws < 0)
      p_direction     <- max(prob_above_zero, prob_below_zero)
      median_estimate <- median(hu_path_draws)

      hu_rows[["c_hu"]] <- data.frame(
        path         = "c_hu",
        var_brms_col = col_c_hu,
        median       = median_estimate,
        mean         = mean(hu_path_draws),
        hdi_lower_94 = hdi_bounds$CI_low,
        hdi_upper_94 = hdi_bounds$CI_high,
        prob_above_0 = prob_above_zero,
        prob_below_0 = prob_below_zero,
        p_direction  = p_direction,
        n_draws      = length(hu_path_draws),
        stringsAsFactors = FALSE
      )
      message(sprintf("  c_hu (%s): median=%.4f P(dir)=%.3f",
                      col_c_hu, median_estimate, p_direction))
    } else {
      message("  WARNING: hu spvar coefficient '", col_c_hu, "' not found in draws.")
    }

    # b_hu: mediator → hu (mediator effect on hurdle probability, logit scale)
    # brms column: b_hu_{dv_no_underscores}_{mediator_name_in_outcome_model_verbatim}
    col_b_hu <- paste0("b_hu_", dv_brms, "_", mediator_name_in_outcome_model)
    if (col_b_hu %in% names(d_hu)) {
      hu_path_draws <- as.numeric(d_hu[[col_b_hu]])

      ## 94% highest density interval, and the two direction probabilities.
      hdi_bounds      <- bayestestR::hdi(hu_path_draws, ci = 0.94)
      prob_above_zero <- mean(hu_path_draws > 0)
      prob_below_zero <- mean(hu_path_draws < 0)
      p_direction     <- max(prob_above_zero, prob_below_zero)
      median_estimate <- median(hu_path_draws)

      hu_rows[["b_hu"]] <- data.frame(
        path         = "b_hu",
        var_brms_col = col_b_hu,
        median       = median_estimate,
        mean         = mean(hu_path_draws),
        hdi_lower_94 = hdi_bounds$CI_low,
        hdi_upper_94 = hdi_bounds$CI_high,
        prob_above_0 = prob_above_zero,
        prob_below_0 = prob_below_zero,
        p_direction  = p_direction,
        n_draws      = length(hu_path_draws),
        stringsAsFactors = FALSE
      )
      message(sprintf("  b_hu (%s): median=%.4f P(dir)=%.3f",
                      col_b_hu, median_estimate, p_direction))
    } else {
      message("  WARNING: hu mediator coefficient '", col_b_hu, "' not found in draws.")
    }

    if (length(hu_rows) > 0) {
      hu_df      <- do.call(rbind, hu_rows)
      hu_csv_dir <- file.path(results_dir, model_name)
      dir.create(hu_csv_dir, recursive = TRUE, showWarnings = FALSE)
      hu_csv     <- file.path(hu_csv_dir, "hu_paths_summary.csv")
      if (convergence_gate$pass) {
        write.csv(hu_df, hu_csv, row.names = FALSE)
        message("Saved: ", hu_csv)
      } else {
        message("[convergence gate] WITHHELD: ", hu_csv)
      }
    }

  }, error = function(e) {
    message("hu-path extraction failed: ", e$message)
  })
}

