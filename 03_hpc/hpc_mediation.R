# "nooutlier" is refused rather than silently ignored.  It dropped rows with |spvar| > 1 in
# Gelman-normalized space (= +-2 raw SD).  That threshold is only meaningful
# against a fixed normalization sample, and there is no longer one at filter
# time: the CSV ships raw and normalization runs after subsetting.  Rather than
# silently redefine which rows it drops, the keyword is refused.  Use "iqr",
# whose 1.5xIQR fence is quantile-based and therefore identical on any positive
# affine rescaling of the column.  Removed from R_SIDE_SUFFIXES in
# master_config.py too, so generation fails first; this stop() is the backstop
# for a stale job file already staged on the cluster.
