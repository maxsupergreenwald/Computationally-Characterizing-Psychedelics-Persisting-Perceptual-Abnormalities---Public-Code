# Rhat / bulk / tail ESS across all model parameters. Constant or deterministic
# parameters (e.g. lprior when no explicit prior is set) return NA; those are
# named in the log rather than silently dropped, and excluded from the min/max.
conv_stats <- tryCatch({
  draws_sum <- posterior::summarise_draws(
    posterior::as_draws_array(fit), "rhat", "ess_bulk", "ess_tail"
  )
  na_vars <- draws_sum$variable[is.na(draws_sum$rhat)]
  if (length(na_vars) > 0) {
    message("NOTE: Rhat is NA for ", length(na_vars), " parameter(s), excluded ",
            "from max_rhat/min ESS: ", paste(na_vars, collapse = ", "))
  }
  data.frame(max_rhat     = max(draws_sum$rhat,     na.rm = TRUE),
             min_bulk_ess = min(draws_sum$ess_bulk, na.rm = TRUE),
             min_tail_ess = min(draws_sum$ess_tail, na.rm = TRUE))
}, error = function(e) {
