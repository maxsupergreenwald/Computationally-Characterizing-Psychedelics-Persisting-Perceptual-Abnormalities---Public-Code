# ── Internal brms response names ──────────────────────────────────────────────
# brms_response_map(): named character vector mapping each response variable's
# ORIGINAL name to the name brms uses INTERNALLY in parameter and draw-column
# names.  E.g. c(vch_nu = "vchnu", caps_vision = "capsvision").
#
# brms strips underscores from RESPONSE names when it builds parameter names
# (predictor names keep theirs).  brmsterms() keeps BOTH names
# on every response — $resp is the internal one, $respform still carries the
# original variable — and pairing them cannot drift from what brms actually did.
#
# Verified against all eight mediation fixtures: identical to the old
# gsub rule on every one, so this is a drop-in with no numerical consequence.
# Also the source of the `resp=` argument for prior_string(), posterior_linpred()
# and posterior_epred(), all of which expect the internal name.
brms_response_map <- function(x) {
  bt <- brmsterms(x)
  stats::setNames(
    vapply(bt$terms, function(term) term$resp,                character(1)),
    vapply(bt$terms, function(term) all.vars(term$respform)[1], character(1))
  )
}

# model_formula: the bivariate formula actually fitted.  Built here rather than
# inline in the brm() call so the same object can be asked for its internal
# response names (brms_response_map) before the fit exists.
model_formula <- bf_mediator + bf_dv + set_rescor(FALSE)

## resp_brms: original response name -> brms-internal response name.
resp_brms <- brms_response_map(model_formula)

# Shape prior: inv_gamma(0.4, 0.3), the brms >= 2.22 default for negbinomial
# families.  Set explicitly for every negbinomial-family response so the fit does
# not depend on the brms version installed on the cluster -- the older
# gamma(0.01, 0.01) default allows shape near zero, which fails to converge for
# caps_vision.
# In bivariate models each response has its own shape parameter; the prior must
# include resp= with the brms-internal response name, which comes from
# resp_brms (see brms_response_map() above) rather than from a hand-applied rule.
negbinom_families_for_shape_prior <- c(
  "negbinomial", "hurdle_negbinomial", "hurdle_negbinom_huvary", "zero_negbinomial"
)
shape_prior_parts <- list()
if (mediator_family %in% negbinom_families_for_shape_prior) {
  med_resp_brms <- resp_brms[[mediator]]
  shape_prior_parts[[length(shape_prior_parts) + 1]] <-
    prior_string("inv_gamma(0.4, 0.3)", class = "shape", resp = med_resp_brms)
  message(paste0("Shape prior inv_gamma(0.4, 0.3) → mediator response: ", med_resp_brms))
}
if (dv_family %in% negbinom_families_for_shape_prior) {
  dv_resp_brms <- resp_brms[[dv]]
  shape_prior_parts[[length(shape_prior_parts) + 1]] <-
    prior_string("inv_gamma(0.4, 0.3)", class = "shape", resp = dv_resp_brms)
  message(paste0("Shape prior inv_gamma(0.4, 0.3) → DV response: ", dv_resp_brms))
}
shape_priors <- if (length(shape_prior_parts) > 0) do.call(rbind, shape_prior_parts) else NULL

fit <- brm(
  model_formula,
  data    = df_clean,
  prior   = shape_priors,
  seed    = seed,
  warmup  = warmup,
  iter    = iter,
  chains  = n_chains,
  cores   = n_cores,
  control = list(adapt_delta = adapt_delta, max_treedepth = max_treedepth)
)

