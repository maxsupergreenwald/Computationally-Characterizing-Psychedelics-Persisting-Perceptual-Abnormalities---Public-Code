##### MC CAUSAL MEDIATION VIA AVERAGE PREDICTIVE COMPARISONS             #####
##############################################################################
#
# How this script computes the mediation estimands.  Written in terms of the
# three roles taken as arguments: spvar (exposure), mediator, dv.
#
# THE FOUR CELLS
#
#   y(a, b) = expected dv with the exposure set to `a` in the OUTCOME model and
#   the mediator drawn from its distribution under exposure `b`.  The two slots
#   move independently; cells like y(x_0, m_1) are counterfactual.
#
#     NIE = y(x_0, m_1) - y(x_0, m_0)     mediated path only
#     NDE = y(x_1, m_0) - y(x_0, m_0)     direct path only
#     TE  = y(x_1, m_1) - y(x_0, m_0)     both
#
#   x_0 = 0 (the mean of spvar; Gelman normalization centres it) and x_1 = 0.5.
#   Gelman divides by 2 SD, so 0.5 normalized units = 1 raw SD.
#
#   NDE here is the TOTAL NDE, which pairs with the PURE NIE: the two sum to the
#   TE exactly.  PURE NDE + TOTAL NIE is the other exact pairing.  Mixing the two
#   pure effects does not sum.
#
# WHY MONTE CARLO INTEGRATION OVER THE MEDIATOR IS REQUIRED
#
#   m_0 and m_1 are distributions, not point values, and dv is a nonlinear
#   function of the mediator (log link on the count, logistic on the hurdle).
#   For nonlinear f, E_M[f(M)] != f(E[M]), and the natural effects are defined
#   over E_M[f(M)].  So for each posterior draw s and subject i we sample
#   L = 1000 mediator values, push EACH through the outcome equation, and
#   average the resulting dv values.
#
#   Averaging the mediator draws first and evaluating once would differ by a
#   Jensen gap — about 4% at these parameter values.  That gap is a BIAS, not
#   noise: raising L shrinks MC noise around E_M[f(M)] but does not move the gap.
#
#   The outcome equation is evaluated analytically at each mediator draw (the
#   closed form below), not simulated.  Drawing a simulated observation on top
#   would average out and change nothing but runtime.  The MEDIATOR draw is
#   required by the estimand and does NOT average out.
#
# ORDER OF OPERATIONS
#
#     for each posterior draw s (S = 16,000):
#       for each subject i (N):
#         average over L mediator draws  ->  y(x,m) for that (s, i)
#       average over the N subjects      ->  one y(x,m) per draw s
#     difference the four cells          ->  S values of NIE (and NDE, TE)
#
#   The three levels do three different jobs:
#     L (inner)  integrates the MEDIATOR's randomness  — required by the estimand
#     N (middle) averages the COVARIATE distribution   — makes effects
#                                                        population-average
#     S (outer)  carries PARAMETER uncertainty         — becomes the HDI
#
# THE OUTCOME EQUATION (hurdle negative binomial — the hardest case supported)
#
#   Two linear predictors rather than one:
#     eta_hu = hu_int + spvar*spvar_hu + mediator*med_hu + covariates   (logit)
#     eta_mu = mu_int + spvar*spvar_mu + mediator*med_mu + covariates   (log)
#
#     E[dv] = (1 - plogis(eta_hu)) * exp(eta_mu) / (1 - P0)
#             \_________ ________/   \________ _________/
#              P(clear the hurdle)    mean of the TRUNCATED NB count
#
#     P0 = (shape / (exp(eta_mu) + shape))^shape
#
#   The /(1 - P0) is the zero-truncation correction: given the hurdle is
#   cleared the count is >= 1, so its mean exceeds exp(eta_mu).  This matches
#   brms::posterior_epred_hurdle_negbinomial().
#
#   A bernoulli DV has a single linear predictor and E[Y] = plogis(eta).  The
#   script dispatches on mediator_family and dv_family at every step, so the
#   same four-cell logic covers zero_inflated_beta / beta / student_t / gaussian
#   / gamma mediators and hurdle_negbinomial / bernoulli / zero_negbinomial /
#   negbinomial / student_t / gaussian outcomes.  Only the inverse link differs.
#
# THREE THINGS THAT ARE SILENTLY WRONG IF GOT WRONG
#
#   1. TWO DISTINCT SHAPE PARAMETERS.  The outcome model's `shape` (in P0) and
#      the mediator model's `shape_med` are different parameters from different
#      equations.  Interchanging them is a serious, silent error.
#
#   2. DRAWS ARE JOINT.  Draw s of every coefficient comes from the same MCMC
#      iteration and carries the joint correlation structure.  Never re-index or
#      shuffle them independently.
#
#   3. MEDIATOR SCALE.  When the mediator model's response and the DV formula's
#      mediator column differ (norm_needed <- mediator_name_in_outcome_model !=
#      mediator), each sampled mediator value must be Gelman-normalized,
#      (M - MEAN0)/(2*SD0), before entering the outcome equation.  MEAN0 and SD0
#      are RECOVERED by regressing the normalized column on the raw one —
#      slope b = 1/(2*SD0), intercept a = -MEAN0/(2*SD0) — which inverts the
#      transform actually applied, whatever constants it used.  Getting them
#      wrong rescales the b path and the NIE with it.  Mediators normalized in
#      place (vch_threshold, vch_beta) skip this entirely.
#
# WHAT COMES OUT
#
#   S values each of NIE, NDE and TE.
#     mean         reported point estimate.  Posterior means are exactly
#                  additive (NIE + NDE = TE); medians are not.
#     median       retained in the CSV so the choice can be revisited without
#                  refitting, but not reported.
#     94% HDI      narrowest interval containing 94% of the S values.
#     p_above_0 /  proportions of the S values above / below zero.
#     p_below_0
#     p_direction  max of the two — the probability the effect has the sign it
#                  appears to have.  A posterior probability, NOT a p-value: it
#                  cannot be read as a false-positive rate, and it can never
#                  fall below 0.5, so values near 0.5 are the "no evidence of
#                  direction" end of the range.
#
#----------------------------------------------------------------------------

#----------------------------------------------------------------------------
#
# PHASES
#   PHASE 1  Setup + design extraction. Constants, covariate parsing, draws,
#            model frame, normalization recovery.
#            -> post_draws, model_frame, S, N, MEAN0, SD0
#   PHASE 2  Mediator model. eta_med at x_0 / x_1, plus that family's
#            dispersion parameters — together, the distributions m_0 and m_1.
#            -> eta_med_x0/x1, shape_med_s / sigma_med_s / nu_med_s / phi_med_s
#   PHASE 3  Outcome model. eta_mu and eta_hu bases, DV dispersion, and the
#            hurdle E[Y] helper.
#            -> eta_mu_base_x0/x1, eta_hu_base_x0/x1, shape_si, calculate_estimate_y_hurdle_negbinom
#   PHASE 4  The L-loop. Per iteration: draw M_x0_l and M_x1_l, rescale them,
#            evaluate E[Y] analytically at each of the four (x, m) cells, and
#            accumulate. The Monte Carlo integration is over the MEDIATOR only;
#            the outcome step is closed-form.
#   PHASE 5  Effects. Divide the four sums by L, average over subjects, form
#            NIE / NDE / TE / PMed, summarise, write mc_mediation_summary.csv.
#   Then, separately: single-path average predictive comparisons (A, B, C'),
#            written to path_counterfactual_summary.csv. NOT the NIE — see the
#            boxed note at that block.
#
#   MEDIATOR FAMILY — how M*_l is drawn (PHASE 2 params, PHASE 4.1 draw, A path)
#     zero_inflated_beta : Bernoulli(zi) mask + Beta;  E[M] = (1-zi)*plogis(eta)
#     beta               : Beta, no mask;              E[M] = plogis(eta)
#     student_t          : rt() with per-draw df;      E[M] = eta
#     gaussian           : rnorm();                    E[M] = eta
#     gamma              : Gamma(shape, rate=shape/mu);E[M] = exp(eta)
#
#   OUTCOME FAMILY — how E[Y] is evaluated (PHASE 3 params, PHASE 4.3, B/C' path)
#     hurdle_negbinom_huvary / hurdle_negbinomial
#                        : E[Y] = (1-plogis(eta_hu)) * exp(eta_mu) / (1 - P0)
#                          P0   = (shape/(exp(eta_mu)+shape))^shape
#     bernoulli          : E[Y] = plogis(eta_mu)
#     zero_negbinomial   : E[Y] = (1-zi) * exp(eta_mu)
#     negbinomial        : E[Y] = exp(eta_mu)
#     student_t/gaussian : E[Y] = eta_mu
#     Unsupported (graceful skip): cumulative/ordinal.
#
#   The raw -> normalized mediator conversion is likewise conditional, on
#   norm_needed <- (mediator_name_in_outcome_model != mediator): mediators normalized in place
#   skip it entirely.
#
# MATRIX SHAPES
#   Every large object is S x N unless the name says otherwise. See the suffix
#   convention above for how _s vectors recycle against _si matrices.
#   sweep(M, 1, v, "*") multiplies row s of M by v[s]; sweep(..., "+") adds.
#
# COMMENT HIERARCHY USED BELOW (fewer #s = more local)
#   #####  phase boundary
#   ####   step within a phase
#   ###    sub-step
#   ##     what a specific variable holds / why it exists
#   #      brief inline note
#
# OUTPUT
#   {results_dir}/{model_name}/mc_mediation_summary.csv
#     effect, median, mean, hdi_low, hdi_high, p_above_0, p_below_0, p_direction,
#     n_draws
#     `mean` is the reported estimate (POINT_ESTIMATE_COL in
#     modules/master_config.py); `median` is retained, not reported.
#     rows: NIE, NDE, TE, PMed
#   {results_dir}/{model_name}/path_counterfactual_summary.csv
#     same schema; rows: A path, B path, C' path
#----------------------------------------------------------------------------

message("\n--- MC Integration Causal Mediation ---")

tryCatch({

  ############################################################################
  ##### PHASE 1 - SETUP + DESIGN EXTRACTION                              #####
  ############################################################################

  #### 1.1 Constants
  ## L: mediator draws per (posterior draw x subject) — the Monte Carlo
  ## integration over the mediator distribution that E_M[f(M)] requires.
  ## MC error ~ 1/sqrt(L). Raising L does NOT change what is being estimated;
  ## it does NOT close the Jensen gap to f(E[M]) either (spec, "L" glossary).
  L        <- 1000   # was 250
  ## x_0 / x_1: the two exposure levels contrasted, in Gelman units.
  ## Gelman normalization divides by 2 SD, so the normalized variable has
  ## SD 0.5 — meaning x_1 = 0.5 is simultaneously "+1 raw SD" and "+1 SD of
  ## the normalized variable". x_0 = 0 is the mean, because it is centred.
  x_0      <- 0.0
  x_1      <- 0.5
  # keep the same seed
  MC_SEED  <- seed

  ## HDI_PROB: project-canonical 94% interval
  HDI_PROB <- 0.94

  ## covariates: the Z_i terms. Every one of them is held FIXED at that
  ## subject's own observed value in all three equations (mediator, mu, hu);
  ## nothing here is ever set to a mean or a mode. Parsed from covs_str, which
  ## contains covariates ONLY — spvar and mediator_name_in_outcome_model are added to the DV
  ## formula separately, so neither can be double-counted here.
  covariates <- if (covs_str == "" || tolower(covs_str) == "none") {
    character(0)
  } else {
    parts <- trimws(strsplit(covs_str, "\\+")[[1]])
    parts[nzchar(parts)]
  }
  print(sprintf("Covariates: %s", paste(covariates, collapse = ", ")))

  #### 1.2 Draws and model frame
  ## model_frame: the data brms actually fitted, AFTER complete.cases() dropped
  ## NAs. N must come from here, not from the original dataframe — brms may have
  ## dropped further rows for missing covariates.
  model_frame <- fit$data

  ## N: subjects i retained in the fit. Columns of every S x N matrix.
  N           <- nrow(model_frame)

  ## counterfactual_newdata(): the fitted model frame with the exposure pinned at
  ## `x` and the mediator -- as it enters the DV formula -- pinned at `m`. Every
  ## covariate keeps that subject's own observed value; nothing is set to a mean,
  ## a mode, or a reference profile.
  ##
  ## When the mediator is normalized IN PLACE, mediator_name_in_outcome_model == mediator and this
  ## also overwrites the mediator's own response column. That is harmless: the
  ## response plays no part in a linear predictor. Verified 2026-08-23 on the
  ## vchthreshold fixture -- zeroing it moves the mediator submodel's eta by
  ## exactly 0.
  counterfactual_newdata <- function(x, m = 0) {
    nd <- model_frame
    nd[[spvar]] <- x
    if (mediator_name_in_outcome_model %in% names(nd)) nd[[mediator_name_in_outcome_model]] <- m
    nd
  }

  ## eta_at(): S x N draws of one submodel's LINK-scale linear predictor,
  ## evaluated by brms on that newdata.
  ##
  ##   transform = FALSE (the default) keeps this on the LINK scale, which is what
  ##   PHASE 4 needs: the mediator term is added here, before any inverse link.
  ##   For the difference between posterior_linpred(), posterior_epred() and
  ##   posterior_predict(), and when each is the right one, see Andrew Heiss,
  ##   "Visualizing the differences between Bayesian posterior predictions, linear
  ##   predictions, and the expectation of posterior predictions" (2022):
  ##   https://www.andrewheiss.com/blog/2022/09/26/guide-visualizing-types-posteriors/#tldr-diagrams-and-cheat-sheets
  ##
  ##   resp / dpar take the brms-INTERNAL response name (see brms_response_map()). Distinguishes between
  ##   the two formulas in the bivariate model (response = DV or response = mediator)
  eta_at <- function(x, resp, dpar = NULL, m = 0) {
    posterior_linpred(object = fit, newdata = counterfactual_newdata(x = x, m = m),
                      resp = resp, dpar = dpar)
  }

  ## post_draws: the posterior. One ROW per draw s, one COLUMN per parameter.
  ## Draw s of every coefficient comes from the SAME MCMC iteration, so the rows
  ## carry the joint correlation structure. Never re-index or shuffle a single
  ## column independently of the others (spec, "S" glossary).
  post_draws  <- as_draws_df(fit)

  ## S: number of posterior draws. Rows of every S x N matrix.
  ## = (iter - warmup) * chains = (10000 - 6000) * 4 = 16000 at project defaults.
  S           <- nrow(post_draws)


  # brms strips underscores only from RESPONSE names; predictor names are verbatim.
  mediator_name_in_brms   <- resp_brms[[mediator]]         # brms-internal mediator response name
  dv_name_in_brms <- resp_brms[[dv]]               # brms-internal DV response name
  print(sprintf("Mediator brms prefix: %s  DV brms prefix: %s", mediator_name_in_brms, dv_name_in_brms))
  # spvar and mediator_name_in_outcome_model used directly as predictor names (underscores PRESERVED)

  message(sprintf("N=%d  S=%d  L=%d  x_0=%.1f  x_1=%.1f", N, S, L, x_0, x_1))
  message(sprintf("Mediator: %s [%s]  DV: %s [%s]", mediator, mediator_family, dv, dv_family))

  #### 1.3 Normalization recovery  — RECOVERS THE GELMAN NORMALIZATION
  ### The mediator MODEL is fitted on the raw mediator column for all except student t distributed variables (a Gamma lives on
  ### the raw scale; a proportion lives in [0,1]), but the DV formula uses
  ### mediator_name_in_outcome_model, which may be the Gelman-normalized variant. Mediator draws
  ### therefore arrive on the raw scale and MUST be rescaled before entering the
  ### DV linear predictor — otherwise the b path, and the NIE with it, is
  ### silently on the wrong scale (spec, "MEAN0 / SD0").
  ###
  ### MEAN0 and SD0 are RECOVERED, not recomputed. Regressing mediator_name_in_outcome_model on
  ### mediator gives slope b = 1/(2*SD0) and intercept a = -MEAN0/(2*SD0), hence
  ###     SD0   = 1/(2b)
  ###     MEAN0 = -a/b
  ### Recovering them this way inverts the Gelman normalization that was 
  ### applied, whatever constants it used, which is what the rescaling in PHASE 4
  ### requires. Assumes mediator_name_in_outcome_model is EXACTLY linear in mediator: true for
  ### Gelman normalization
  norm_needed <- (mediator_name_in_outcome_model != mediator) # check to see if the mediator is normalized in place (no separate normalization step)
  ## MEAN0 / SD0: the recovered centring and scaling constants
  MEAN0 <- NA_real_
  SD0 <- NA_real_
  if (norm_needed) {
    ## Regress the normalized column on the raw one. Because the transform was
    ## affine, this line recovers it exactly (residuals ~1e-15 on all mediators).
    norm_lm        <- lm(as.formula(paste(mediator_name_in_outcome_model, "~", mediator)), data = model_frame)
    norm_slope     <- coef(norm_lm)[2]   #  b = 1 / (2 * SD0)
    norm_intercept <- coef(norm_lm)[1]   #  a = -MEAN0 / (2 * SD0)

    ## Invert the two coefficients back into the normalization constants:
    ##   MEAN0 = -a / b      SD0 = 1 / (2b)
    ## The 2 is Gelman normalization dividing by 2 SD rather than 1 SD.
    MEAN0          <- -norm_intercept / norm_slope
    gelman_sd_multiplier <- 2            # Gelman normalization divides by 2 SD, not 1
    SD0            <- 1.0 / (gelman_sd_multiplier * norm_slope)
    message(sprintf("Norm recovery: MEAN0=%.4f  SD0=%.4f", MEAN0, SD0))
  } else {
    message("Mediator is in-place normalized: no separate normalization step.")
  }

  ############################################################################
  ##### PHASE 2 - MEDIATOR MODEL                                         #####
  ##### Goal: eta_med at x_0 and at x_1, plus this family's dispersion   #####
  ##### parameters — together these define the distributions m_0 and m_1 #####
  ############################################################################

  #### 2.1 Mediator linear predictor
  ###     eta_med = med_int + spvar*spvar_med + covariates          (spec)
  ##
  ## eta_med_x0 / eta_med_x1: S x N mediator linear predictor on the LINK scale,
  ## with the exposure set to x_0 and to x_1 respectively. Applying this family's
  ## inverse link gives the MEAN (E[mediator]) of m_0 / m_1; the dispersion parameters below
  ## give their spread. Together those are the distributions m_0 and m_1 - which
  ## are never materialised as objects, only drawn from, in PHASE 4.
  ##
  ## The intercept and the a-path slope are no longer pulled out by name: brms
  ## puts them into eta itself. The a-path COEFFICIENT is still reported, from
  ## the block that writes path_coefficients_summary.csv.
  eta_med_x0 <- eta_at(x = x_0, resp = mediator_name_in_brms, dpar = NULL, m = 0)
  eta_med_x1 <- eta_at(x = x_1, resp = mediator_name_in_brms, dpar = NULL, m = 0)

  # Mediator-family-specific extra parameters
  if (mediator_family == "zero_inflated_beta") { # for VCH Rate
    phi_med_s   <- as.numeric(post_draws[[paste0("phi_", mediator_name_in_brms)]])
    zi_med_s <- as.numeric(post_draws[[paste0("zi_",  mediator_name_in_brms)]])
    # mu on logit scale already in eta_med; shape params for Beta
    mu_med_x0 <- plogis(eta_med_x0)
    mu_med_x1 <- plogis(eta_med_x1)
    phi_med_si   <- matrix(rep(phi_med_s, N), S, N)
    zi_med_si    <- matrix(rep(zi_med_s, N), S, N)
    beta_shape1_x0  <- mu_med_x0 * phi_med_si
    beta_shape2_x0   <- (1 - mu_med_x0) * phi_med_si
    beta_shape1_x1  <- mu_med_x1 * phi_med_si
    beta_shape2_x1   <- (1 - mu_med_x1) * phi_med_si
    message(sprintf("  ZIBeta: median phi=%.2f  median zi=%.3f",
                    median(phi_med_s), median(zi_med_s)))

  } else if (mediator_family == "student_t") { # threshold, beta
    sigma_med_s <- as.numeric(post_draws[[paste0("sigma_", mediator_name_in_brms)]])
    nu_med_s    <- as.numeric(post_draws[[paste0("nu_",    mediator_name_in_brms)]])
    sigma_med_si <- matrix(rep(sigma_med_s, N), S, N)
    nu_med_si    <- matrix(rep(nu_med_s,    N), S, N)
    message(sprintf("  Student-t: median sigma=%.3f  median nu=%.3f",
                    median(sigma_med_s), median(nu_med_s)))

  } else if (mediator_family == "gamma") { #nu
    shape_med_s   <- as.numeric(post_draws[[paste0("shape_", mediator_name_in_brms)]])
    shape_med_si <- matrix(rep(shape_med_s, N), S, N)
    message(sprintf("  Gamma: median shape=%.3f", median(shape_med_s)))

  } else if (mediator_family == "beta") {
    # Pure Beta (no ZI): logit link, precision phi. E[M|eta] = plogis(eta).
    phi_med_s     <- as.numeric(post_draws[[paste0("phi_", mediator_name_in_brms)]])
    mu_med_x0 <- plogis(eta_med_x0)
    mu_med_x1 <- plogis(eta_med_x1)
    phi_med_si   <- matrix(rep(phi_med_s, N), S, N)
    beta_shape1_x0  <- mu_med_x0 * phi_med_si
    beta_shape2_x0   <- (1 - mu_med_x0) * phi_med_si
    beta_shape1_x1  <- mu_med_x1 * phi_med_si
    beta_shape2_x1   <- (1 - mu_med_x1) * phi_med_si
    message(sprintf("  Beta: median phi=%.2f", median(phi_med_s)))

  }  else {
    message(sprintf(
      "  MC integration and path counterfactuals SKIPPED: mediator_family '%s' not supported. Supported: zero_inflated_beta, beta, student_t, gaussian, gamma.",
      mediator_family))
    stop("__SKIP__")
  }

  # Now we have the eta_med values for X0 and X1 and the parameters for the mediator's family so that we can
  # define the correct distributions m_0 and m_1 and sample from them L times in PHASE 4
  # calculating the overall E[Y] each time before then averaging to get the E[Y] when the mediator is 
  # mean vs. elevated by the spvar to get an idea of the indirect/mediated effect on Y!
  # HOORAY!

  ############################################################################
  ##### PHASE 3 - OUTCOME MODEL                                          #####
  ##### Goal: the count (mu) and hurdle (hu) linear predictors at x_0    #####
  ##### and x_1, WITHOUT their mediator terms, plus the DV dispersion.   #####
  ############################################################################
  ### The mediator term is deliberately NOT included here. It cannot be: the
  ### mediator value is not known until it is drawn inside the PHASE 4 loop,
  ### and it is drawn twice (under m_0 and under m_1) against each of these two
  ### bases. Hence the "_base" in the names — these are eta_mu and eta_hu less
  ### their mediator contribution, which PHASE 4 adds via
  ###     sweep(M_norm, 1, med_mu_s, "*")   /   sweep(M_norm, 1, med_hu_s, "*")
  ### Separating the x slot from the m slot is what makes the counterfactual
  ### cells y(x_0, m_1) and y(x_1, m_0) computable.

  #### 3.1 Count (mu) submodel — log link
  ###     eta_mu = mu_int + spvar*spvar_mu + mediator*med_mu + covariates  (spec)

  ## med_mu_s: length S - change in log(NB mean) per 1 unit of the mediator, ON
  ## THE DV FORMULA'S SCALE (hence the rescaling in 4.2, not the raw scale).
  ## THIS IS THE "b" PATH. Spec name: med_mu.
  ##
  ## This one coefficient IS still read by name, because PHASE 4 needs it as a
  ## scalar: the mediator is DRAWN there, taking a different value for every
  ## (draw, subject), and posterior_linpred() evaluates all draws against one
  ## newdata, so it cannot supply a per-draw mediator. eta_mu_base below is
  ## therefore eta WITHOUT the mediator term, and PHASE 4 adds med_mu_s * m.
  ##
  ## That addition is exact only if the DV is linear in the mediator. It is - the
  ## mediator enters the DV formula as a plain main effect - and the assertion
  ## below proves it against brms rather than trusting the formula string.
  med_mu_s  <- as.numeric(post_draws[[paste0("b_", dv_name_in_brms, "_", mediator_name_in_outcome_model)]])

  ## eta_mu_base_x0/x1: S x N, LINK (log) scale, mediator pinned at 0 - i.e. at
  ## the mediator's own raw mean, since mediator_name_in_outcome_model is Gelman-centred.
  eta_mu_base_x0 <- eta_at(x = x_0, resp = dv_name_in_brms, dpar = NULL, m = 0)
  eta_mu_base_x1 <- eta_at(x = x_1, resp = dv_name_in_brms, dpar = NULL, m = 0)

  ## Linearity guard. Moving the mediator from 0 to 1 must shift eta by exactly
  ## med_mu_s for every subject. A non-constant shift means the DV formula gained
  ## an interaction with the mediator, or a spline or mo() wrapper on it, and
  ## PHASE 4's "eta_mu_base + med_mu_s * m" would then be wrong. Fail loudly here
  ## rather than silently reporting a mis-specified NIE.
  eta_mu_shift_per_unit_mediator <-
    eta_at(x = x_0, resp = dv_name_in_brms, dpar = NULL, m = 1) - eta_mu_base_x0
  max_linearity_error <- max(abs(sweep(eta_mu_shift_per_unit_mediator, 1, med_mu_s, "-")))
  if (!is.finite(max_linearity_error) || max_linearity_error > 1e-8) {
    stop(sprintf(paste0("DV is not linear in the mediator: moving %s from 0 to 1 shifts eta by ",
                        "up to %.3g away from b_%s_%s. PHASE 4 adds the mediator term ",
                        "linearly and would be wrong. Check the DV formula for an ",
                        "interaction with, or a transform of, the mediator."),
                 mediator_name_in_outcome_model, max_linearity_error, dv_name_in_brms, mediator_name_in_outcome_model))
  }

  #### 3.2 DV family flags — select the E[Y] route used in PHASE 4
  ## negbinomial / zero_negbinomial / gaussian are still branched on here but
  ## are no longer fitted by get_brms_family().
  ## Removed 2026-08-23 (Max): use_zi_nb_dv ("zero_negbinomial") and
  ## use_negbinomial_dv ("negbinomial"), and the unused "gaussian" string from
  ## use_gaussian_dv. get_brms_family() has no switch entry for either
  ## negbinomial family, so no job could ever reach those branches; "gaussian" is
  ## in the switch but no VARIABLE_REGISTRY entry declares it. "student_t" KEEPS
  ## this branch - it shares the identity link and is the most-declared family in
  ## the registry.
  use_hurdle_dv    <- dv_family %in% c("hurdle_negbinom_huvary", "hurdle_negbinomial")
  use_bernoulli_dv <- (dv_family == "bernoulli")
  use_gaussian_dv  <- (dv_family == "student_t")   # identity link: E[Y] = eta_mu


  if (use_hurdle_dv) {
    # E[Y] = (1 - plogis(eta_hu)) * exp(eta_mu) / (1 - P0), P0 = (shape/(mu+shape))^shape
    # (zero-truncated count component; see calculate_estimate_y_hurdle_negbinom() below)

    ## med_hu_s: length S - the mediator's coefficient in the HURDLE submodel,
    ## needed as a scalar for the same reason med_mu_s is. Absent (and therefore
    ## zero) when hu is intercept-only rather than varying.
    med_hu_col <- paste0("b_hu_", dv_name_in_brms, "_", mediator_name_in_outcome_model)
    med_hu_s   <- if (med_hu_col %in% names(post_draws)) as.numeric(post_draws[[med_hu_col]]) else rep(0, S)

    ## eta_hu_base_x0/x1: S x N, LOGIT scale, mediator pinned at 0.
    ## dpar = "hu" selects the hurdle submodel. No dv_hu_zi_varying branch is
    ## needed: when hu is intercept-only brms returns the intercept for every
    ## subject, which is exactly what the old cov_hu_si = 0 path produced.
    eta_hu_base_x0 <- eta_at(x = x_0, resp = dv_name_in_brms, dpar = "hu", m = 0)
    eta_hu_base_x1 <- eta_at(x = x_1, resp = dv_name_in_brms, dpar = "hu", m = 0)

  } else if (use_bernoulli_dv) {
    # bernoulli: E[Y] = plogis(eta_mu) — no extra DV parameters needed.
    NULL
  } else if (use_gaussian_dv) {
    # student_t: identity link — no extra DV parameters needed beyond mu_base.
    NULL
  } else {
    # Unsupported DV family (e.g. cumulative/ordinal): skip gracefully.
    message(sprintf(
      "  MC integration and path counterfactuals SKIPPED: dv_family '%s' not supported (ordinal not yet implemented).",
      dv_family))
    stop("__SKIP__")
  }

  # ── DV shape parameter ──────────────────────────────────────────────────────
  # Needed by the analytic hurdle E[Y] below, which renormalises the untruncated
  # NB mean by the zero-truncation factor 1/(1 - P0), P0 = (shape/(mu+shape))^shape.
  # Parameter names include the response prefix with underscores stripped:
  # e.g. "shape_capsvision".
  # (The DV's sigma / nu were only ever needed by the removed observation-noise
  # route: for identity-link families they scale the noise, never E[Y].)
  if (use_hurdle_dv) {
    shape_col <- paste0("shape_", dv_name_in_brms)
    shape_s   <- as.numeric(post_draws[[shape_col]])
    shape_si <- matrix(rep(shape_s, N), S, N)
  }

  # E[Y] for hurdle_negbinomial, per brms posterior_epred_hurdle_negbinomial():
  #     mu / (1 - (shape/(mu+shape))^shape) * (1 - hu)
  # The count component is a ZERO-TRUNCATED negative binomial, so mu (the mean of
  # the *untruncated* NB) must be renormalised by 1 - P0, where P0 =
  # (shape/(mu+shape))^shape is the NB's own probability of a zero. Dropping the
  # 1/(1 - P0) factor would UNDERESTIMATE E[Y] and every contrast derived from it.
  # Ref: https://github.com/paul-buerkner/brms/blob/master/R/posterior_epred.R

  ### THE canonical hurdle-NB E[Y] for this file. Both the four-cell loop in
  ### PHASE 4 and the single-path APCs at the end call it, so the two output
  ### CSVs cannot drift onto different formulas.
  ### Arguments are LINK-SCALE linear predictors WITH the mediator term already
  ### added; shape_si is captured from the enclosing scope.

  calculate_estimate_y_hurdle_negbinom <- function(eta_mu, eta_hu) {
    ## E[Y] = (1 - plogis(eta_hu)) * exp(eta_mu) / (1 - P0)
    ## built one step at a time below.

    ### Step 1 — invert the log link to get the mean of the UNTRUNCATED NB.
    ### This is NOT E[Y]: it is the count component's mean if zeros were still
    ### possible, which under a hurdle they are not.
    mean_count_untruncated_nb <- exp(eta_mu)

    ### Step 2 — invert the logit link on the hurdle submodel. plogis() gives
    ### P(structural zero); its complement is P(clear the hurdle).
    prob_structural_zero <- plogis(eta_hu)
    prob_clear_hurdle    <- 1 - prob_structural_zero

    ### Step 3 — P0, the probability the untruncated NB would itself have
    ### returned a zero:  P0 = (shape / (mu + shape))^shape.
    ### shape_si is the DV's dispersion parameter (S x N), captured from the
    ### enclosing scope. It is NOT the mediator's shape — those are two
    ### different parameters from two different equations.
    nb_mean_plus_shape          <- mean_count_untruncated_nb + shape_si
    nb_zero_probability_base    <- shape_si / nb_mean_plus_shape
    prob_untruncated_nb_is_zero <- nb_zero_probability_base^shape_si

    ### Step 4 — renormalise by 1 - P0 to get the mean of the ZERO-TRUNCATED
    ### count. Given the hurdle is cleared the count is guaranteed >= 1, so its
    ### mean is HIGHER than the untruncated mean. Dropping this factor would
    ### underestimate E[Y] and every contrast derived from it.
    zero_truncation_renormalizer <- 1 - prob_untruncated_nb_is_zero
    mean_count_truncated_nb      <- mean_count_untruncated_nb / zero_truncation_renormalizer

    ### Step 5 — E[Y] = P(clear the hurdle) x mean of the truncated count.
    prob_clear_hurdle * mean_count_truncated_nb
  }


  ############################################################################
  ##### PHASE 4 - THE L-LOOP: MC INTEGRATION OVER THE MEDIATOR            #####
  ##### L iterations. Each draws one mediator value under m_0 and one    #####
  ##### under m_1, rescales both onto the DV formula's scale, evaluates  #####
  ##### E[Y] analytically at all four y(x, m) cells, and accumulates.     #####
  ############################################################################
  ### WHY THE LOOP EXISTS (spec: "E_M[f(M)] is NOT f(E[M])").
  ### m_0 and m_1 are DISTRIBUTIONS, and E[Y] is a nonlinear function of the
  ### mediator (log link on the count, logistic on the hurdle). The natural
  ### effects are defined over the distribution of the counterfactual mediator,
  ### i.e. E_M[f(M)]. Plugging the mediator's mean into the outcome once would
  ### give f(E[M]), which differs by a Jensen gap that is a BIAS, not noise:
  ### raising L shrinks the MC noise around E_M[f(M)] but leaves the gap to
  ### f(E[M]) exactly where it was. So: draw, push each draw through the outcome
  ### equation, and average the OUTCOMES — never average the mediator draws.

  #### 4.0 Initiate Accumulators - running SUMS over the L iterations, divided by L in
  #### PHASE 5 to become means. Naming: y_x{0,1}_m{0,1} =
  ####   first slot  = the exposure value used in the OUTCOME model
  ####   second slot = the exposure value the MEDIATOR was drawn under
  #### The two slots move independently. Cells where they disagree are
  #### counterfactual: no real subject has the exposure at x_0 while their
  #### mediator behaves as if it were at x_1.
  y_x0_m0_sum <- matrix(0.0, S, N)   ## y(x_0, m_0) - the reference cell (mean SP exposure and associated mean mediator)
  y_x0_m1_sum <- matrix(0.0, S, N)   ## y(x_0, m_1) - mediator moved only -> NIE
  y_x1_m0_sum <- matrix(0.0, S, N)   ## y(x_1, m_0) - exposure moved only
                                     ## This is the PURE NDE's treatment cell.
                                     ## Since the NDE became the TOTAL form
                                     ## (Entry 003, 2026-08-22) no reported
                                     ## quantity reads it, so it is dead weight
                                     ## in the loop. KEPT DELIBERATELY (Max,
                                     ## 2026-08-22): it is one of the four cells
                                     ## the spec defines, and keeping it means
                                     ## the pure NDE — or reporting both
                                     ## decompositions — stays one line away.
                                     ## If it is ever removed, note that this
                                     ## accumulator, its /L division in 5.1 and
                                     ## its five per-family branch lines in 4.3
                                     ## all go together.
  y_x1_m1_sum <- matrix(0.0, S, N)   ## y(x_1, m_1) - both moved          -> TE

  set.seed(MC_SEED)
  message(sprintf("Running MC integration: L=%d draws per (s,i)...", L))
  t0_mc <- proc.time()["elapsed"]

  for (l in seq_len(L)) {
    if (l %% 50 == 0) {
      el <- proc.time()["elapsed"] - t0_mc
      message(sprintf("  l=%3d/%d [%.0fs elapsed, ~%.0fs remaining]",
                      l, L, el, el / l * (L - l)))
    }

    # ── 4.1 Draw one mediator value per (s, i) from m_0 and from m_1 ────────
    # M_x0_l ~ m_0 and M_x1_l ~ m_1: the l-th draw, on the mediator model's own
    # (raw) scale. They come from DIFFERENT distributions, so they are and must
    # be independent draws.
    #
    # Each draw is reused by two of the four cells. Since the NDE became the
    # TOTAL natural direct effect (Entry 003, 2026-08-22) the pair that shares a
    # draw is y(x_1,m_1) and y(x_0,m_1), both built from M_x1_l — which is why
    # most of the NDE's MC error cancels. Before that change the shared draw was
    # M_x0_l, across y(x_0,m_0) and y(x_1,m_0); this comment said so and had not
    # been updated. Corrected 2026-08-22.

    if (mediator_family == "zero_inflated_beta") {
      # Mirrors brms:::posterior_predict_zero_inflated_beta(), which is
      #   ifelse(runif(n) < zi, 0, rbeta(n, mu * phi, (1 - mu) * phi)).
      # Ref: https://github.com/paul-buerkner/brms/blob/master/R/posterior_predict.R
      ## Step 1 — a uniform per (draw s, participant i), used to decide which
      ## cells are structural zeros. Drawn for x_0 first, then x_1: the RNG
      ## consumption order matters, because MC_SEED is fixed.
      u_x0_l <- matrix(runif(S * N), S, N)
      u_x1_l <- matrix(runif(S * N), S, N)

      ## Step 2 — a cell is a structural zero when its uniform falls below that
      ## draw's zero-inflation probability.
      is_zero_x0_l <- u_x0_l < zi_med_si
      is_zero_x1_l <- u_x1_l < zi_med_si

      ## Step 3 — the Beta part, from the shape1/shape2 built in PHASE 2.
      M_x0_l <- matrix(rbeta(S * N, as.vector(beta_shape1_x0), as.vector(beta_shape2_x0)), S, N)
      M_x1_l <- matrix(rbeta(S * N, as.vector(beta_shape1_x1), as.vector(beta_shape2_x1)), S, N)

      ## Step 4 — apply the zero mask.
      M_x0_l[is_zero_x0_l] <- 0.0
      M_x1_l[is_zero_x1_l] <- 0.0

    } else if (mediator_family == "student_t") {
      # brms's own exported sampler for this family: rstudent_t(n, df, mu, sigma)
      # is mu + sigma * rt(n, df). sigma is the SCALE, not the SD
      # (SD = sigma * sqrt(nu/(nu-2))). mu is eta_med, the mean under the identity link.
      # Ref: https://github.com/paul-buerkner/brms/blob/master/R/distributions.R
      # x_0 drawn before x_1; order matters because MC_SEED is fixed.
      M_x0_l <- matrix(data = brms::rstudent_t(n     = S * N,
                                               df    = as.vector(nu_med_si),
                                               mu    = as.vector(eta_med_x0),
                                               sigma = as.vector(sigma_med_si)),
                       nrow = S, ncol = N)
      M_x1_l <- matrix(data = brms::rstudent_t(n     = S * N,
                                               df    = as.vector(nu_med_si),
                                               mu    = as.vector(eta_med_x1),
                                               sigma = as.vector(sigma_med_si)),
                       nrow = S, ncol = N)

    } else if (mediator_family == "gamma") {
      # brms parameterises Gamma by MEAN and SHAPE:
      #     M ~ Gamma(mean = exp(eta_med), shape = shape_med)
      #     Var(M) = mean^2 / shape
      # rgamma() is parameterised by SHAPE and SCALE, and the two relate by
      #     scale = mean / shape
      # This is exactly what brms itself does when it samples this family (see
      # brms:::posterior_predict_gamma, which computes scale <- mu / shape and
      # calls rgamma with it), so the draws below match the model's own
      # predictive distribution.
      #
      # shape_med_si is S x N carrying draw s's shape in every cell of row s
      # (built above from shape_med_s); exp(eta_med_x0) is S x N, so `scale` is
      # evaluated elementwise per (draw s, subject i). rgamma() takes the
      # matrices column-major, which is the same (s, i) layout.
      ## Step 1 — invert the log link to get the Gamma MEAN per (s, i).
      gamma_mean_x0  <- exp(eta_med_x0)
      gamma_mean_x1  <- exp(eta_med_x1)

      ## Step 2 — convert brms' (mean, shape) to rgamma's (shape, scale).
      gamma_scale_x0 <- gamma_mean_x0 / shape_med_si
      gamma_scale_x1 <- gamma_mean_x1 / shape_med_si

      ## Step 3 — draw. x_0 before x_1; the order matters under a fixed MC_SEED.
      M_x0_l <- matrix(rgamma(S * N, shape = shape_med_si, scale = gamma_scale_x0), S, N)
      M_x1_l <- matrix(rgamma(S * N, shape = shape_med_si, scale = gamma_scale_x1), S, N)

    } else if (mediator_family == "beta") {
      # Pure Beta: same as ZIBeta draws but no zero-inflation mask
      M_x0_l <- matrix(rbeta(S * N, as.vector(beta_shape1_x0), as.vector(beta_shape2_x0)), S, N)
      M_x1_l <- matrix(rbeta(S * N, as.vector(beta_shape1_x1), as.vector(beta_shape2_x1)), S, N)

    }

    #### 4.2 Gelman normalize the mediator if it wasnt normalized in the spvar -> mediator model to match 
    # mediator values used in the main DV (outcome) model -- to actually estimate E[Y] from mediator. 
    ## M_x0_l_norm / M_x1_l_norm: S x N, Gelman scale — (M - MEAN0) / (2*SD0)
    if (norm_needed) {
      ## Gelman normalization: subtract the centring constant, then divide by
      ## TWO SDs (not one). MEAN0 / SD0 were recovered in PHASE 1.3.
      gelman_denominator <- 2 * SD0
      M_x0_l_centered    <- M_x0_l - MEAN0
      M_x1_l_centered    <- M_x1_l - MEAN0
      M_x0_l_norm        <- M_x0_l_centered / gelman_denominator
      M_x1_l_norm        <- M_x1_l_centered / gelman_denominator
    } else {
      # mediator already in-place normalized: DV model uses the same column
      M_x0_l_norm <- M_x0_l
      M_x1_l_norm <- M_x1_l
    }

    # ── 4.3 Evaluate E[Y] at all four cells and accumulate ──────────────────
    # E[Y | x, M*_l, Z_i, theta_s] = g^{-1}(eta) in closed form. No outcome-step
    # RNG: the mediator draw in 4.1 is the only stochastic element in this loop.
    #
    # Read each block as the four cells of the spec, in this fixed order:
    #   y(x_0, m_0)   eta base at x_0  +  med coef * M_x0_l_norm
    #   y(x_0, m_1)   eta base at x_0  +  med coef * M_x1_l_norm   <- only m moved
    #   y(x_1, m_0)   eta base at x_1  +  med coef * M_x0_l_norm   <- only x moved
    #   y(x_1, m_1)   eta base at x_1  +  med coef * M_x1_l_norm   <- both moved

    ### 4.3a The mediator's contribution to the COUNT linear predictor.
    ### sweep(M, 1, v, "*") multiplies row s of M by v[s], so this is the b path
    ### (med_mu_s, one value per draw) times this iteration's mediator draw.
    ### There are only TWO of them — one per mediator distribution — and each is
    ### reused by two of the four cells. That reuse is the point: it is what
    ### lets y(x_1, m_1) and y(x_0, m_1) — the two cells the TOTAL NDE
    ### differences — share a mediator draw, so most of its MC error cancels.
    med_mu_contribution_m0 <- sweep(M_x0_l_norm, 1, med_mu_s, "*")
    med_mu_contribution_m1 <- sweep(M_x1_l_norm, 1, med_mu_s, "*")

    ### 4.3b The four COUNT linear predictors, one per (x, m) cell. First
    ### subscript = the exposure used in the OUTCOME model; second = the
    ### exposure the MEDIATOR was drawn under. The two move independently.
    eta_mu_x0_m0 <- eta_mu_base_x0 + med_mu_contribution_m0   # reference cell
    eta_mu_x0_m1 <- eta_mu_base_x0 + med_mu_contribution_m1   # only mediator moved
    eta_mu_x1_m0 <- eta_mu_base_x1 + med_mu_contribution_m0   # only spvar moved
    eta_mu_x1_m1 <- eta_mu_base_x1 + med_mu_contribution_m1   # both moved

    if (use_hurdle_dv) {
      ### 4.3c For the hurdle families the SAME rescaled mediator draw also
      ### enters the HURDLE linear predictor, with its own coefficient
      ### (med_hu_s, not med_mu_s) — the mediator moves the probability of a
      ### zero and the size of a nonzero count simultaneously, which is why
      ### E[Y] must combine both submodels.
      med_hu_contribution_m0 <- sweep(M_x0_l_norm, 1, med_hu_s, "*")
      med_hu_contribution_m1 <- sweep(M_x1_l_norm, 1, med_hu_s, "*")

      eta_hu_x0_m0 <- eta_hu_base_x0 + med_hu_contribution_m0
      eta_hu_x0_m1 <- eta_hu_base_x0 + med_hu_contribution_m1
      eta_hu_x1_m0 <- eta_hu_base_x1 + med_hu_contribution_m0
      eta_hu_x1_m1 <- eta_hu_base_x1 + med_hu_contribution_m1

      ### 4.3d Evaluate E[Y] at each cell and add it to that cell's running sum.
      y_x0_m0_sum <- y_x0_m0_sum + calculate_estimate_y_hurdle_negbinom(eta_mu_x0_m0, eta_hu_x0_m0)
      y_x0_m1_sum <- y_x0_m1_sum + calculate_estimate_y_hurdle_negbinom(eta_mu_x0_m1, eta_hu_x0_m1)
      y_x1_m0_sum <- y_x1_m0_sum + calculate_estimate_y_hurdle_negbinom(eta_mu_x1_m0, eta_hu_x1_m0)
      y_x1_m1_sum <- y_x1_m1_sum + calculate_estimate_y_hurdle_negbinom(eta_mu_x1_m1, eta_hu_x1_m1)

    } else if (use_bernoulli_dv) {
      ### Single linear predictor, logit link: E[Y] = plogis(eta_mu).
      y_x0_m0_sum <- y_x0_m0_sum + plogis(eta_mu_x0_m0)
      y_x0_m1_sum <- y_x0_m1_sum + plogis(eta_mu_x0_m1)
      y_x1_m0_sum <- y_x1_m0_sum + plogis(eta_mu_x1_m0)
      y_x1_m1_sum <- y_x1_m1_sum + plogis(eta_mu_x1_m1)

    } else if (use_gaussian_dv) {
      ### Identity link: E[Y] = eta_mu. sigma / nu do not enter E[Y].
      y_x0_m0_sum <- y_x0_m0_sum + eta_mu_x0_m0
      y_x0_m1_sum <- y_x0_m1_sum + eta_mu_x0_m1
      y_x1_m0_sum <- y_x1_m0_sum + eta_mu_x1_m0
      y_x1_m1_sum <- y_x1_m1_sum + eta_mu_x1_m1
    }

  }  
  message(sprintf("MC loop done: %.1fs", proc.time()["elapsed"] - t0_mc))
  # end MC loop!!!!!!
  ##############################################################################################################

  ############################################################################
  ##### PHASE 5 - EFFECTS                                                #####
  ############################################################################
  ### The three nested averaging levels, and what each is for (spec):
  ###   L (innermost, done in 5.1)  integrates over the MEDIATOR's randomness.
  ###                               Required by the estimand; does NOT average
  ###                               away, because E[Y] is nonlinear in M.
  ###   N (middle, done in 5.2)     averages over the COVARIATE distribution.
  ###                               Makes the effect population-average rather
  ###                               than specific to one covariate profile.
  ###   S (outermost, never)        carries PARAMETER uncertainty. It is never
  ###                               averaged over — it is what becomes the HDI.

  #### 5.1 L-average: turn the accumulated sums into the four cells (S x N each)
  ## Each is now E_M[ E[Y | x, M, Z_i, theta_s] ] for its (x, m) combination.
  y_x0_m0 <- y_x0_m0_sum / L
  y_x0_m1 <- y_x0_m1_sum / L
  y_x1_m0 <- y_x1_m0_sum / L
  y_x1_m1 <- y_x1_m1_sum / L

  #### 5.2 N-average and contrast: one value per posterior draw
  ## rowMeans() averages over SUBJECTS (columns), leaving draws (rows). Each
  ## subject keeps their own covariates — that is the "average" in average
  ## predictive comparison, and it is what makes these population-average
  ## effects. Differencing then averaging is identical to averaging then
  ## differencing, since both operations are linear.
  ##
  ## The three contrasts, exactly as the spec defines them:
  ##   NIE = y(x_0, m_1) - y(x_0, m_0)   mediated path only  (PURE  NIE)
  ##   NDE = y(x_1, m_1) - y(x_0, m_1)   direct path only    (TOTAL NDE)
  ##   TE  = y(x_1, m_1) - y(x_0, m_0)   both
  ## Note the exposure stays at x_0 in BOTH terms of the NIE. Holding it there
  ## while moving only the mediator is what isolates the mediated path; if the
  ## exposure also moved to x_1, that difference would be the TOTAL effect.
  ##
  ## This TOTAL-NDE / PURE-NIE pairing is chosen because it DECOMPOSES EXACTLY:
  ##   [y(x_1,m_1) - y(x_0,m_1)] + [y(x_0,m_1) - y(x_0,m_0)] = y(x_1,m_1) - y(x_0,m_0)
  ## the interior terms cancel identically, so NDE + NIE = TE to machine
  ## precision with no residual mediated-interaction term. The other exact
  ## pairing is PURE NDE + TOTAL NIE. Mixing the two pure effects does NOT sum.
  ##
  ## NIE and TE difference an M_x0_l-built cell against an M_x1_l-built one
  ## (independent draws), so they inherit MC variance from both. NDE shares a
  ## mediator draw across both its cells, so its MC error largely cancels — note
  ## the shared draw is now M_x1_l (both y(x_1,m_1) and y(x_0,m_1) are built
  ## from it), where the former pure-NDE form shared M_x0_l.
  ## Each contrast is formed per (draw, participant) first, then averaged over
  ## participants. Differencing-then-averaging and averaging-then-differencing
  ## give the same answer here because both operations are linear.
  nie_per_participant <- y_x0_m1 - y_x0_m0   # PURE  NIE: only the mediator moved
  nde_per_participant <- y_x1_m1 - y_x0_m1   # TOTAL NDE: only the exposure moved
  te_per_participant  <- y_x1_m1 - y_x0_m0   # TE:        both moved

  ## rowMeans() averages over SUBJECTS (columns), leaving one value per draw.
  nie_s <- rowMeans(nie_per_participant)
  ## TOTAL NDE, which pairs with the PURE NIE above: the two sum to the TE.
  nde_s <- rowMeans(nde_per_participant)
  te_s  <- rowMeans(te_per_participant)

  ## pmed_s: the PURE NIE over the TE, per draw.
  ##
  ## When the TE's posterior straddles zero the ratio is Cauchy-like, so neither
  ## its median nor its HDI is meaningful.  TE_NEAR_ZERO_GUARD sets PMed to NA
  ## for any draw whose |TE| falls below it; effect_summary_hpc() then excludes
  ## those draws from the PMed summary.  Read PMed only for a model whose TE is
  ## clearly separated from zero.
  TE_NEAR_ZERO_GUARD     <- 1e-10
  te_is_effectively_zero <- abs(te_s) < TE_NEAR_ZERO_GUARD

  ## Computed for every draw; ifelse() discards the values at the guarded ones.
  proportion_mediated_raw <- nie_s / te_s

  pmed_s <- ifelse(te_is_effectively_zero, NA_real_, proportion_mediated_raw)

  mc_results <- do.call(rbind, list(
    effect_summary_hpc(nie_s,  paste0("NIE  Indirect (via ", mediator, ")"), HDI_PROB),
    effect_summary_hpc(nde_s,  paste0("NDE  Direct (", spvar, " → ", dv, ")"), HDI_PROB),
    effect_summary_hpc(te_s,   "TE   Total Effect",                            HDI_PROB),
    effect_summary_hpc(pmed_s, "PMed Proportion mediated",                     HDI_PROB)
  ))

  # Print summary
  cat("\n", strrep("=", 72), "\n", sep="")
  cat(sprintf("CAUSAL MEDIATION (MC, L=%d): %s → %s → %s\n", L, spvar, mediator, dv))
  cat(sprintf("Dose contrast: x_0=%.1f  x_1=%.1f  (+1 raw SD)\n", x_0, x_1))
  cat(sprintf("N=%d  S=%d  L=%d\n", N, S, L))
  cat(strrep("=", 72), "\n\n", sep="")
  print(mc_results[, c("effect","median","hdi_low","hdi_high","p_direction")], row.names=FALSE)
  cat("\n")

  mc_out_dir <- file.path(results_dir, model_name)
  dir.create(mc_out_dir, recursive = TRUE, showWarnings = FALSE)
  mc_csv <- file.path(mc_out_dir, "mc_mediation_summary.csv")
  if (convergence_gate$pass) {
    write.csv(mc_results, mc_csv, row.names = FALSE)
    message("Saved: ", mc_csv)
  } else {
    message("[convergence gate] WITHHELD: ", mc_csv)
  }

  # ── Average predictive comparisons for individual paths (response scale) ─────
  # Named "counterfactual" only for filename compatibility
  # (path_counterfactual_summary.csv). These are model-based predictive contrasts under the
  # fitted model ("average comparisons") in the sense of Arel-Bundock, Greifer & Heiss (2024),
  # "How to Interpret Statistical Models Using marginaleffects for R and Python",
  # Journal of Statistical Software 111(9), 1-32, doi:10.18637/jss.v111.i09 --
  # set the focal quantity to a counterfactual value for every observed unit,
  # holding that unit's own covariates fixed, predict on the response scale, and
  # average the differences. 
  #
  # Computes marginal response-scale effects for individual paths by evaluating the
  # DV and mediator expected values, computed deterministically:
  #
  #   A path : E[Mediator(response) | X=x_1, Z_i] − E[Mediator | X=x_0, Z_i]
  #            = +1 raw SD spvar effect on the mediator (mediator's own response scale)
  #   B path : E[DV | M_norm=x_1, X=x_0, Z_i] − E[DV | M_norm=x_0, X=x_0, Z_i]
  #            = +1 raw SD mediator effect on DV, spvar held at its mean (x_0=0)
  #              M_norm=x_0 (=0) = mediator at raw mean; M_norm=x_1 (=0.5) = +1 raw SD.
  #              x_1 is reused for the mediator's shift so that B and C' are the
  #              same size of move; see the note at the code below.
  #   C' path: E[DV | M_norm=0.0, X=x_1, Z_i] − E[DV | M_norm=0.0, X=x_0, Z_i]
  #            = +1 raw SD spvar effect on DV, mediator fixed at its mean
  #
  # For hurdle_negbinom_huvary, E[Y] = (1-plogis(η_hu)) × exp(η_mu) / (1 - P0)
  # integrates BOTH mu and hu submodels automatically — no separate B_hu/C'_hu
  # paths needed. Computed by calculate_estimate_y_hurdle_negbinom(), the same helper the NIE/NDE/TE
  # block uses, so both output CSVs are on identical formulas.
  # eta_mu_base_x0/x1 and eta_hu_base_x0/x1 (already S×N matrices from MC block above)
  # contain all covariate + intercept + spvar contributions for each draw × observation.
  #
  # All effects are averaged over observations (marginalizes over covariate distribution).
  # Each resulting S-vector is summarized with effect_summary_hpc() (94% HDI, pd).
  #
  # Saved to: {results_dir}/{model_name}/path_counterfactual_summary.csv
  # Columns: effect, median, mean, hdi_low, hdi_high, p_above_0, p_below_0, p_direction, n_draws
  #          `mean` is the reported estimate (POINT_ESTIMATE_COL in
  #          modules/master_config.py); `median` is retained, not reported.
  # Same format as mc_mediation_summary.csv (same effect_summary_hpc helper).
  # Scale notes:
  #   A path  — mediator response scale: proportions for beta/ZIBeta; raw units for gamma;
  #             Gelman-normalized units for student_t/gaussian (2 raw SDs = 1 unit)
  #   B path  — DV response scale; consistent with mc_mediation_summary.csv NIE/NDE scale
  #   C' path — DV response scale; directly comparable to NDE in mc_mediation_summary.csv
  # ──────────────────────────────────────────────────────────────────────────────
  message("Computing counterfactual path summaries (deterministic, response scale)...")
  tryCatch({
    cf_rows <- list()

    # ┌──────────────────────────────────────────────────────────────────────┐
    # │ THIS IS NOT THE NIE. Do not read this block as y(x, m).              │
    # │                                                                      │
    # │ The spec's four cells — y(x_0,m_0), y(x_0,m_1), y(x_1,m_0),          │
    # │ y(x_1,m_1) — are computed in PHASE 4 above, where the mediator is    │
    # │ DRAWN L = 1000 times from the distributions m_0 and m_1 and the      │
    # │ outcome is averaged over those draws. Those cells feed               │
    # │ mc_mediation_summary.csv.                                            │
    # │                                                                      │
    # │ THIS block is a separate, supplementary output. It reports what the  │
    # │ individual a / b / c-prime paths are worth on the response scale, by │
    # │ holding the mediator FIXED at a single value (0 or x_1 on the Gelman │
    # │ scale) rather than drawing it. No L-loop, no E_M[.] integral, no     │
    # │ Jensen correction — none apply, because nothing is integrated over.  │
    # │ These three numbers do NOT decompose the TE and must never be        │
    # │ substituted for NIE / NDE. They go to a different file,              │
    # │ path_counterfactual_summary.csv.                                     │
    # │                                                                      │
    # │ `Mfix0` / `Mfix1` are FIXED MEDIATOR VALUES and mean something       │
    # │ different from the m_0 / m_1 DISTRIBUTIONS above.                    │
    # └──────────────────────────────────────────────────────────────────────┘
    #
    # Because the mediator is FIXED here, every cell is an ordinary prediction at
    # a modified newdata — which is exactly what posterior_epred() computes, on
    # the response scale, using each submodel's own mean function. That is why
    # this block carries no family branching: hurdle_negbinomial's
    # mu / (1 - (shape/(mu+shape))^shape) * (1 - hu), bernoulli's plogis(eta),
    # gamma's exp(eta), zero_inflated_beta's (1 - zi) * plogis(eta) and student-t's
    # identity are all applied by brms. Before 2026-08-23 each was transcribed by
    # hand behind a `dv_family` / `mediator_family` if-chain.
    # ?posterior_epred.brmsfit; and Andrew Heiss (2022) on epred vs linpred vs
    # predict: https://www.andrewheiss.com/blog/2022/09/26/guide-visualizing-types-posteriors/#tldr-diagrams-and-cheat-sheets
    #
    # The three contrasts, each averaged over participants (rowMeans) to give one
    # value per posterior draw:
    #
    #   A path : E[M | X=x_1, Z_i] − E[M | X=x_0, Z_i]
    #            +1 raw SD of spvar, on the MEDIATOR's own response scale
    #   B path : E[Y | M_norm=x_1, X=x_0, Z_i] − E[Y | M_norm=0, X=x_0, Z_i]
    #            +1 raw SD of the mediator, exposure held at its mean
    #   C' path: E[Y | M_norm=0, X=x_1, Z_i] − E[Y | M_norm=0, X=x_0, Z_i]
    #            +1 raw SD of spvar, mediator held at its mean
    #
    # x_1 is reused as the mediator's shift, rather than a separate literal. It is
    # the same step — "+1 raw SD on a Gelman-normalized variable", i.e. +0.5
    # normalized units because Gelman divides by 2 SD — applied to the MEDIATOR
    # instead of the exposure. Sharing the constant is what keeps the B path and
    # the C' path the same size of move, and that is the only reason the two are
    # comparable to each other or to the NIE / NDE. Widen x_1 and both follow.

    ## expected_response(): S x N draws of E[response] on the RESPONSE scale, with
    ## the exposure pinned at `x` and the mediator-as-DV-predictor pinned at `m`.
    ## Shares counterfactual_newdata() with the MC block, so both outputs are on
    ## one definition of "hold everything else at its observed value".
    expected_response <- function(x, m, resp) {
      posterior_epred(object = fit, newdata = counterfactual_newdata(x = x, m = m), resp = resp)
    }

    # ── A path ────────────────────────────────────────────────────────────────
    ## The mediator submodel has no mediator term, so `m` is immaterial here.
    a_path_s <- rowMeans(expected_response(x = x_1, m = 0, resp = mediator_name_in_brms) -
                         expected_response(x = x_0, m = 0, resp = mediator_name_in_brms))
    cf_rows[["a"]] <- effect_summary_hpc(a_path_s, "A path", HDI_PROB)
    message(sprintf("  A path: median=%.4f pd=%.3f",
                    cf_rows[["a"]]$median, cf_rows[["a"]]$p_direction))

    # ── B and C' paths ────────────────────────────────────────────────────────
    ## Baseline cell, shared by both contrasts: exposure at its mean, mediator at
    ## its mean. Computed once.
    expected_y_x0_Mfix0 <- expected_response(x = x_0, m = 0,   resp = dv_name_in_brms)
    expected_y_x0_Mfix1 <- expected_response(x = x_0, m = x_1, resp = dv_name_in_brms)   # B: mediator +1 SD
    expected_y_x1_Mfix0 <- expected_response(x = x_1, m = 0,   resp = dv_name_in_brms)   # C': spvar +1 SD

    ## Contrast per (draw, participant), then average over participants.
    b_path_s       <- rowMeans(expected_y_x0_Mfix1 - expected_y_x0_Mfix0)
    c_prime_path_s <- rowMeans(expected_y_x1_Mfix0 - expected_y_x0_Mfix0)

    cf_rows[["b"]]       <- effect_summary_hpc(b_path_s,       "B path",  HDI_PROB)
    cf_rows[["c_prime"]] <- effect_summary_hpc(c_prime_path_s, "C' path", HDI_PROB)
    message(sprintf("  B path:  median=%.4f pd=%.3f",
                    cf_rows[["b"]]$median, cf_rows[["b"]]$p_direction))
    message(sprintf("  C' path: median=%.4f pd=%.3f",
                    cf_rows[["c_prime"]]$median, cf_rows[["c_prime"]]$p_direction))


    cf_df  <- do.call(rbind, cf_rows)
    cf_dir <- file.path(results_dir, model_name)
    dir.create(cf_dir, recursive = TRUE, showWarnings = FALSE)
    cf_csv <- file.path(cf_dir, "path_counterfactual_summary.csv")
    if (convergence_gate$pass) {
      write.csv(cf_df, cf_csv, row.names = FALSE)
      message("Saved: ", cf_csv)
    } else {
      message("[convergence gate] WITHHELD: ", cf_csv)
    }

  }, error = function(e) {
    message("Counterfactual path computation failed: ", e$message)
  })

}, error = function(e) {
  if (grepl("__SKIP__", conditionMessage(e), fixed = TRUE)) {
    invisible(NULL)  # graceful skip; reason already printed before stop("__SKIP__")
  } else {
    message("MC integration failed: ", e$message)
    message("  If this is a 'not yet implemented' family combination, add support in hpc_mediation.R.")
  }
})

message(paste0("SUCCESS: ", model_name))
message(paste0("Results in: ", file.path(results_dir, model_name)))
