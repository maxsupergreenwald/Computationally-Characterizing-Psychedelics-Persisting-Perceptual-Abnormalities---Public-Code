# --------------------------------------------------------------------------
# Map family strings to brms family objects
# --------------------------------------------------------------------------
get_brms_family <- function(fam_str) {
  # "ordinal" and "cumulative" are synonyms: both map to brms cumulative() family.
  # VARIABLE_REGISTRY in master_config.py uses "ordinal" as the canonical string
  # (see Bürkner & Vuorre 2019, https://journals.sagepub.com/doi/10.1177/2515245918823199).
  # nonsp_predictors.R also uses "ordinal"; accept both strings here for consistency.
  #
  # "hurdle_negbinom_huvary": hurdle_negbinomial() family where the hu submodel also
  # varies with the full predictor set (added June 2026 for caps_vision). The _huvary
  # suffix is handled at the bf() construction level — this function returns the same
  # brms family object as "hurdle_negbinomial". The difference is in bf_dv construction.
  switch(fam_str,
    "student_t"               = student(link = "identity"),
    "gaussian"                = gaussian(link = "identity"),
    "beta"                    = Beta(),
    "zero_inflated_beta"      = zero_inflated_beta(),
    "gamma"                   = Gamma(link = "log"),
    "bernoulli"               = bernoulli(link = "logit"),
    "hurdle_negbinom_huvary"  = hurdle_negbinomial(),
    stop(paste0("Unknown family: '", fam_str, "'. ",
                "Valid: student_t, gaussian, beta, zero_inflated_beta, gamma, ",
                "zero_negbinomial, bernoulli, cumulative/ordinal, negbinomial, lognormal, ",
                "hurdle_negbinomial, hurdle_negbinom_huvary"))
  )
}

# ── MC integration helper functions ─────────────────────────────────────────
# effect_summary_hpc: compute posterior mean and median, 94% HDI, and direction
# probabilities.
# Both point estimates are stored. `mean` is the REPORTED estimate and the one
# every downstream script reads (POINT_ESTIMATE_COL in modules/master_config.py);
# `median` is recorded alongside it so the choice can be revisited from CSVs
# already on disk without refitting. They differ whenever the posterior is skewed,
# and only the mean is additive across effects (median NIE + median NDE does not
# equal median TE even when the per-draw values sum exactly), which is why the
# mean is reported.
# NB the run-log lines below still print the median; that is cosmetic and the
# labels say so. Both columns go to the CSV either way.
effect_summary_hpc <- function(draws, label, hdi_prob = 0.94) {
  ## Drop NAs first: pmed_s deliberately generates them where the TE is too
  ## close to zero to divide by, and every statistic below must ignore those.
  draws <- draws[!is.na(draws)]

  ## The 94% highest density interval — the narrowest interval containing 94%
  ## of the draws. $CI_low / $CI_high are its two bounds.
  hdi_bounds <- bayestestR::hdi(draws, ci = hdi_prob)

  ## Direction probabilities. p_direction is whichever of the two is larger:
  ## the posterior probability that the effect has the sign it appears to have.
  ## It can never fall below 0.5, so 0.5 is the "no evidence of direction" end
  ## of its range, not a small number. It is NOT a p-value.
  prob_above_zero <- mean(draws > 0)
  prob_below_zero <- mean(draws < 0)
  p_direction     <- max(prob_above_zero, prob_below_zero)

  data.frame(
    effect      = label,
    median      = median(draws),
    mean        = mean(draws),
    hdi_low     = hdi_bounds$CI_low,
    hdi_high    = hdi_bounds$CI_high,
    p_above_0   = prob_above_zero,
    p_below_0   = prob_below_zero,
    p_direction = p_direction,
    n_draws     = length(draws),
    stringsAsFactors = FALSE
  )
}

# build_cov_contribution_hpc() was REMOVED 2026-08-23.  It built the S x N
# covariate contribution to a linear predictor by matching draw-column names by
# prefix — a reimplementation of brms's design matrix that could, and in
# nonsp_predictors.R's copy did, silently disagree with it (monotonic mo() terms
# scored as zero for every subject).  Every caller now uses eta_at(), which wraps
# posterior_linpred() and lets brms build the linear predictor it actually fitted.

mediator_fam <- get_brms_family(mediator_family)
dv_fam       <- get_brms_family(dv_family)

# --------------------------------------------------------------------------
# Determine if DV needs a varying hu submodel
# --------------------------------------------------------------------------
# "hurdle_negbinom_huvary": hu submodel varies with full predictor set (dv_rhs).
# All other families (including plain "hurdle_negbinomial"): hu is intercept-only.
dv_hu_zi_varying <- (dv_family == "hurdle_negbinom_huvary")

# --------------------------------------------------------------------------
# Build brms bivariate formulas
# --------------------------------------------------------------------------
bf_mediator <- bf(as.formula(mediator_formula_str), family = mediator_fam)

if (dv_hu_zi_varying) {
  # Add varying hu submodel with the same RHS as the count (mu) submodel.
  # This allows the predictor, mediator, and covariates to affect BOTH the
  # probability of any nonzero response AND the expected count given non-zero.
  hu_formula_str <- paste0("hu ~ ", dv_rhs)
  message("DV family is hurdle_negbinom_huvary — adding hu formula: ", hu_formula_str)
  bf_dv <- bf(as.formula(dv_formula_str), as.formula(hu_formula_str), family = dv_fam)
} else {
  bf_dv <- bf(as.formula(dv_formula_str), family = dv_fam)
}

