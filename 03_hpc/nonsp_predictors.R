# `binary_factor_vars` is already loaded — categorical_factor_vars.R is sourced
# in the block above, because gelman_normalize_df() needs the same list to know
# which variables to exclude from normalization.

alerts <- character(0)

for (v in binary_factor_vars) {
  if (v %in% names(df_new)) {
    # Keep sex_v2 in its original coding (1/2), but collapse inhalants 2 -> 0.
    if (v == "inhalants_lifetime") {
      x <- suppressWarnings(as.numeric(as.character(df_new[[v]])))
      x[!is.na(x) & x == 2] <- 0
      df_new[[v]] <- x
      print("  [binary prep] inhalants_lifetime recoded: 2 -> 0")
    }

    df_new[[v]] <- as.factor(df_new[[v]])

    lvl_counts <- table(df_new[[v]], useNA = "no")
    n_lvls <- nlevels(df_new[[v]])
    counts_str <- paste(names(lvl_counts), as.integer(lvl_counts), sep = ":", collapse = ", ")
    print(paste0("  [binary prep] ", v, " levels=", n_lvls, " counts={", counts_str, "}"))

    if (n_lvls != 2) {
      alerts <- c(alerts, paste0(v, " has ", n_lvls, " levels (expected 2)."))
    }
    if (length(lvl_counts) > 0 && any(lvl_counts < 30)) {
      small <- paste(names(lvl_counts)[lvl_counts < 30], as.integer(lvl_counts[lvl_counts < 30]), sep = ":", collapse = ", ")
      alerts <- c(alerts, paste0(v, " has level count(s) < 30 -> ", small))
    }
  }
}

