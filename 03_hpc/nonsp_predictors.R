# -----------------------------------------------------------------------
# Factor covariates — sourced from categorical_factor_vars.R, which is
# auto-generated by generate_hpc_jobs.py from modules/master_config.py.
# To add or remove a variable, edit CATEGORICAL_FACTOR_VARS in master_config.py
# and re-run generate_hpc_jobs.py.  Do NOT edit the list here directly.
