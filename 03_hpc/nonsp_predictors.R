# ── 94% Highest Density Interval ───────────────────────────────────────────
# Returns the 94% highest density interval of a posterior as a named pair,
# c(lower = ..., upper = ...).
#
# Thin wrapper over bayestestR::hdi(). It exists for two reasons: callers here
# want a plain named numeric pair rather than the one-row data.frame bayestestR
# returns, and callers want a non-finite draw to be an error rather than
# something quietly dropped.
#
# Fails loudly on non-finite input. Posterior draws should never be NA, NaN, or
# Inf; when they are, it signals an upstream problem with the fit (for example a
# shape parameter collapsing toward 0 in a hurdle model). Dropping those draws
# silently would report an interval computed from a smaller, different posterior
# than the one the model actually produced.
# Condition class carried by every compute_hdi_94() failure. Call sites that wrap
# model steps in tryCatch() re-raise on this class rather than logging and moving
# on, so a bad posterior fails the job instead of silently producing no output.
HDI_ERROR_CLASS <- "hdi_integrity_error"

compute_hdi_94 <- function(samples, cred_mass = 0.94) {
  if (!is.numeric(samples)) {
    stop(errorCondition(
      paste0("compute_hdi_94(): expected a numeric vector, got ",
             paste(class(samples), collapse = "/"), "."),
      class = HDI_ERROR_CLASS))
  }

  n_bad <- sum(!is.finite(samples))
  if (n_bad > 0L) {
    stop(errorCondition(sprintf(
      paste0("compute_hdi_94(): %d of %d draws are NA/NaN/Inf. Posterior draws ",
             "should always be finite, so this signals an upstream problem with ",
             "the fit. Investigate the model rather than filtering the draws."),
      n_bad, length(samples)), class = HDI_ERROR_CLASS))
  }

  if (length(samples) < 2L) {
    stop(errorCondition(sprintf(
      "compute_hdi_94(): need at least 2 draws to form an interval, got %d.",
      length(samples)), class = HDI_ERROR_CLASS))
  }

  h <- bayestestR::hdi(samples, ci = cred_mass)

  # bayestestR warns and returns NA when ceiling(ci * n) >= n. That is a real
  # failure for our purposes, so promote it to an error.
  if (!is.finite(h$CI_low) || !is.finite(h$CI_high)) {
    stop(errorCondition(sprintf(
      paste0("compute_hdi_94(): bayestestR::hdi() returned a non-finite interval for ",
             "n = %d draws at ci = %s. The sample is too short for the requested ",
             "credible mass."),
      length(samples), format(cred_mass)), class = HDI_ERROR_CLASS))
  }

  c(lower = h$CI_low, upper = h$CI_high)
}

# ── Average predictive comparison ─────────────────────────────────────────────
# average_predictive_comparison(): returns the S-vector of population-average
# contrasts  E[Y | spvar = x1, Z_i] - E[Y | spvar = x0, Z_i],  one value per
# posterior draw.
#
# Set the focal predictor to a counterfactual value for every observed unit, hold
# that unit's own covariates at their observed values, predict on the RESPONSE
# scale, and average the differences.  This is the "average comparison" of
# Arel-Bundock, Greifer & Heiss (2024), *How to Interpret Statistical Models
# Using marginaleffects for R and Python*, JSS 111(9), 1-32,
# doi:10.18637/jss.v111.i09.
#
#     for each posterior draw s (S of them):
#       for each subject i (N of them):  E[Y | x0, Z_i]  and  E[Y | x1, Z_i]
#       average the difference over the N subjects   -> one delta for draw s
#     -> S values of delta
#
#   N (inner)  averages over the COVARIATE distribution, which is what makes the
#              effect population-average rather than specific to one profile.
#   S (outer)  carries PARAMETER uncertainty.  Never averaged over; it is what
#              becomes the HDI.
#
# WHY posterior_epred() RATHER THAN A HAND-BUILT LINEAR PREDICTOR
#   posterior_epred() returns draws of E[Y] already on the response scale, using
#   this family's own mean function -- for hurdle_negbinomial that is
#   mu / (1 - (shape/(mu+shape))^shape) * (1 - hu), i.e. both submodels and the
#   zero-truncation renormalisation; for bernoulli it is plogis(eta).  See
#   ?posterior_epred.brmsfit.  For what separates epred from posterior_linpred()
#   and posterior_predict(), and when each is the right one, see Andrew Heiss,
#   "Visualizing the differences between Bayesian posterior predictions, linear
#   predictions, and the expectation of posterior predictions" (2022):
#   https://www.andrewheiss.com/blog/2022/09/26/guide-visualizing-types-posteriors/#tldr-diagrams-and-cheat-sheets
#
#   Assembling eta by hand instead means re-deriving every family's mean function
#   AND matching every term type brms supports.  Until 2026-08-23 this script did
#   exactly that, and scored monotonic mo() covariates as ZERO for every subject:
#   it searched the draws for a column named "b_mo(<var>)", while brms names them
#   "bsp_mo<var>" and "simo_mo<var>1[j]".  The prefix match simply returned
#   nothing and no error was raised.  On a real caps_vision fit that halved the
#   APC.  posterior_epred() cannot drift from the fitted model in this way,
#   because it *is* the fitted model.
#
# ARGUMENTS
#   fit     a fitted brmsfit (single-response; this script fits no mv models)
#   spvar   focal predictor column name, verbatim as it appears in fit$data
#   x0, x1  the two focal values in Gelman-normalised units.  Gelman divides by
#           2 SD, so the default x1 - x0 = 0.5 is exactly +1 raw SD.
#
# RETURNS   numeric vector of length S (one delta per posterior draw)
average_predictive_comparison <- function(fit, spvar, x0 = 0.0, x1 = 0.5) {
  ## fit$data is the model frame brms actually fitted, AFTER complete.cases()
  ## dropped incomplete rows.  Using it rather than the original dataframe is
  ## what makes N the ESTIMATION sample size.
  newdata_x0 <- fit$data
  newdata_x1 <- fit$data

  if (!spvar %in% names(newdata_x0)) {
    stop("average_predictive_comparison(): focal predictor '", spvar,
         "' is not a column of fit$data.  Columns present: ",
         paste(names(newdata_x0), collapse = ", "))
  }

  ## Only the focal predictor moves.  Every covariate keeps its observed value in
  ## BOTH frames -- nothing is set to a mean, a mode, or a reference profile.
  newdata_x0[[spvar]] <- x0
  newdata_x1[[spvar]] <- x1

  ## S x N draws of E[Y] on the RESPONSE scale, one row per posterior draw.
  expected_y_x0 <- posterior_epred(fit, newdata = newdata_x0)
  expected_y_x1 <- posterior_epred(fit, newdata = newdata_x1)

  ## rowMeans() averages over SUBJECTS (columns), leaving one delta per draw.
  rowMeans(expected_y_x1 - expected_y_x0)
}

### ACTUAL MAIN FUNCTION FOR FITTING AND APC ESTIMATION
# adapt_delta: OPTIONAL 10th CLI argument, default 0.98 (the project-wide
# value).  Added 2026-08-31 so a single model can be re-fitted at a tighter
# step-size adaptation without changing it for every model in the pipeline.
# Every existing 9-argument job line therefore behaves exactly as before.
# Raise it when a fit is blocked by a small number of divergent transitions and
# nothing else -- the convergence gate allows zero, and a funnel-prone geometry
# (e.g. hurdle_negbinom_huvary on a thin covariate set) can produce one or two
# even when Rhat and ESS are excellent.
brms_master <- function (settings, dataframe, dv=NA, iter=4000, sp_and_covs, covs, spvar, factororno, adapt_delta=0.98) {

  # ── Path helper ──────────────────────────────────────────────────────────────
  # When spvar is provided: nest results under {spvar}/{covs}/
  # When spvar is "" (covariate-only mode): save directly under {covs}/
  base_dir <- if (nchar(spvar) > 0) file.path(spvar, covs) else covs

  # Parse covariate names from formula RHS — used for per-covariate diagnostics
  all_covariates <- trimws(strsplit(sp_and_covs, "\\+")[[1]])

  # ── Factor handling: only relevant when focal predictor = factor ───────────
  if (nchar(spvar) > 0 && factororno == "factor") {
    print("She's a FACTOR!")
    dataframe[[spvar]] <- as.factor(dataframe[[spvar]])
  }

  # Initialize hu submodel formula string; only set for hurdle families with varying hu.
  # The model_formula construction below checks this to include the second bf() formula.
  hu_formula_str <- NULL

  # Define the formula string, family, and link function from `settings`.
  # Only the five families this pipeline actually uses are supported. Anything
  # else is a configuration error and stops here, rather than failing later with
  # an obscure "object 'formula_str' not found".
  if (settings == "student_t"){
    formula_str <- paste0(dv," ~ ",sp_and_covs)
    fam_to_use = student(link = "identity")
    dataframe <- dataframe[complete.cases(dataframe[[dv]]), ]
  } else if (settings == "logistic" || settings == "bernoulli"){
    # "bernoulli" is the canonical string emitted by generate_hpc_jobs.py for
    # binary (0/1) DVs; "logistic" is an older alias. Both select the same family.
    formula_str <- paste0(dv," ~ ",sp_and_covs)
    fam_to_use = bernoulli(link="logit")
    dataframe <- dataframe[complete.cases(dataframe[[dv]]), ]
  } else if (settings == "zero_inflated_beta"){
    formula_str <- paste0(dv," ~ ",sp_and_covs)
    fam_to_use = zero_inflated_beta()
    dataframe <- dataframe[complete.cases(dataframe[[dv]]), ]
  } else if (settings == "gamma"){
    formula_str <- paste0(dv," ~ ",sp_and_covs)
    fam_to_use = Gamma(link = "log")
    dataframe <- dataframe[complete.cases(dataframe[[dv]]), ]
  } else if (settings == "beta"){
    # Beta() for proportion DVs bounded strictly inside (0,1) — currently only
    # vch_bl_yes_75 (hit rate at 75% contrast; observed range 0.389-0.9999).
    # The RAW column is fitted here, not vch_bl_yes_75_normalized: Beta requires
    # (0,1) and the Gelman-normalized column is negative for most subjects.
    # No rescaling is applied; the DV is already a proportion.
    formula_str <- paste0(dv," ~ ",sp_and_covs)
    fam_to_use = Beta()
    dataframe <- dataframe[complete.cases(dataframe[[dv]]), ]
  } else if (settings == "hurdle_negbinom_huvary") {
    # hurdle_negbinomial() with a varying hu submodel.
    # The hu submodel uses the SAME RHS as the mu (count) submodel, so the predictor
    # (and all covariates) affect BOTH the probability of any nonzero response (hu)
    # AND the expected count given a nonzero response (mu).
    formula_str    <- paste0(dv, " ~ ", sp_and_covs)
    hu_formula_str <- paste0("hu ~ ", sp_and_covs)
    fam_to_use     <- hurdle_negbinomial()
    dataframe      <- dataframe[complete.cases(dataframe[[dv]]), ]
  } else {
    stop(sprintf(
      paste0("Unsupported settings value '%s' for DV '%s'. Supported: student_t, ",
             "logistic/bernoulli, zero_inflated_beta, beta, gamma, hurdle_negbinom_huvary. ",
             "Check VARIABLE_REGISTRY['distribution'] in master_config.py."),
      settings, dv), call. = FALSE)
  }

  # Build brms formula object. For hurdle families with varying hu, include the second
  # distributional-parameter formula. For all others, use a single formula.
  if (!is.null(hu_formula_str)) {
    model_formula <- bf(as.formula(formula_str), as.formula(hu_formula_str))
  } else {
    model_formula <- bf(as.formula(formula_str))
  }

  ### Fit the model
  # Shape prior: inv_gamma(0.4, 0.3), the brms >= 2.22 default for negbinomial
  # families.  Set explicitly so the fit does not depend on the brms version
  # installed -- the older gamma(0.01, 0.01) default allows shape near zero,
  # which fails to converge for caps_vision.
  shape_prior <- if (settings == "hurdle_negbinom_huvary") {
    prior(inv_gamma(0.4, 0.3), class = shape)
  } else {
    NULL
  }
  fit1 <- brm(model_formula,
              data = dataframe,
              family = fam_to_use,
              prior = shape_prior,
              seed = seed,
              warmup = warmup,
              iter = iter,
              chains = chains,
              cores = 4,
              control = list(adapt_delta = adapt_delta, max_treedepth = 12)) 
  # Define relative paths
  fit_dir            <- file.path("results", "fits")
  convergence_dir    <- file.path("convergence_tests")
  pp_dir             <- file.path("pp_checks")
  summary_dir        <- file.path("results", "summary_dfs")
  posterior_draws_dir <- file.path("results", "posterior_draws")
  diagnostic_dir     <- file.path("results", "diagnostics")

  # Create directories using base_dir
  dir.create(file.path(base_dir, fit_dir),             recursive = TRUE, showWarnings = FALSE)
  dir.create(file.path(base_dir, convergence_dir),     recursive = TRUE, showWarnings = FALSE)
  dir.create(file.path(base_dir, pp_dir),              recursive = TRUE, showWarnings = FALSE)
  dir.create(file.path(base_dir, summary_dir),         recursive = TRUE, showWarnings = FALSE)
  dir.create(file.path(base_dir, posterior_draws_dir), recursive = TRUE, showWarnings = FALSE)
  dir.create(file.path(base_dir, diagnostic_dir),      recursive = TRUE, showWarnings = FALSE)

  print("saving posterior draws dataframe...")
  draws <- as_draws_df(fit1)
  write_csv(draws, file.path(base_dir, posterior_draws_dir, paste0(dv, "_draws.csv")))

  print("saving the fit...")
  save(fit1, file = file.path(base_dir, fit_dir, paste0(dv,"_fit.RData")))

  # ── Convergence gate ─────────────────────────────────────────────────────────
  # Decides whether this model's SUMMARY RESULT TABLES may be written:
  #   results/summary_dfs/{dv}.csv  and  results/summary_dfs/{dv}_counterfactual.csv
  # Nothing else is withheld — the fit above, the diagnostics CSV and every
  # diagnostic plot are written either way, so a blocked model still leaves a
  # complete record of why it was blocked.  Thresholds and rationale live in
  # convergence_gate.R.
  #
  # Focal parameters only: b_{spvar}, plus b_hu_{spvar} when the hu submodel
  # carries the predictors.  A covariate-only run (spvar == "") names none, which
  # leaves the Rhat/ESS half vacuous; the divergence check still applies.
  convergence_gate <- check_convergence_gate(
    fit1,
    gate_parameters_nonsp(spvar, has_hu = (settings == "hurdle_negbinom_huvary"))
  )
  report_convergence_gate(convergence_gate,
                          label = paste0(dv, " ~ ", sp_and_covs, "  [", settings, "]"),
                          emit  = print)

  print("nabbing summary...")
  summarized <- summary(fit1)

  # ── Convergence traces ───────────────────────────────────────────────────────
  # With a focal spvar: one trace for that predictor (original behavior).
  # Without spvar: one trace file per covariate.
  print("running convergence test...")
  if (nchar(spvar) > 0) {
    convergence_test <- plot(fit1, variable = spvar, regex = TRUE)[[1]]
    ggsave(file.path(base_dir, convergence_dir, paste0(dv,"_convergence_plot.png")),
           convergence_test, width = 10, height = 8, dpi = 800)
  } else {
    print("  Saving per-covariate convergence traces...")
    for (cov in all_covariates) {
      tryCatch({
        # brms strips underscores internally; match against stripped name
        stripped <- gsub("_", "", cov)
        cov_plots <- plot(fit1, variable = stripped, regex = TRUE)
        if (length(cov_plots) > 0) {
          ggsave(
            file.path(base_dir, convergence_dir, paste0(dv, "_", cov, "_convergence.png")),
            cov_plots[[1]], width = 10, height = 8, dpi = 800
          )
        }
      }, error = function(e) {
        print(paste0("  Convergence trace for ", cov, " failed: ", e$message))
      })
    }
  }

  # calculate rhat, check if any are unsatisfactory, and save them.
  print("checking rhat...")
  rhat_combined <- c(summarized$fixed[, "Rhat"], summarized$random$record_id[, "Rhat"])

  if (length(rhat_combined[abs(1 - rhat_combined) > 0.1]) > 0){
    print("UH OH! One of the fixed or random parameters has an rhat more than 0.1 from 1!!!")
  }

  save(rhat_combined, file = file.path(base_dir, convergence_dir, paste0(dv,"_rhat_combined.RData")))

  ##### Results saved
  print("Great! Now we just need to get a results df...")
  result_df <- summarized$fixed

  result_df$var <- rownames(result_df)
  result_df$model <- settings
  result_df$covariates <- covs
  result_df$N <- nobs(fit1)

  # Programmatic divergent-transition count via brms::nuts_params() — more reliable than
  # rstan::get_num_divergent(fit1$fit), which is deprecated in newer rstan and requires
  # dropping to the raw Stan fit layer. nuts_params() works directly on the brms object.
  result_df$num_divergents <- sum(
    brms::nuts_params(fit1)$Parameter == "divergent__" &
    brms::nuts_params(fit1)$Value      == 1
  )

  # Extract all population-level parameter names.
  # Regular fixed effects use a 'b_' prefix; monotonic effects (mo()) use 'bsp_'.
  # Both need identical HDI and posterior-probability treatment.
  fixed_effect_vars <- grep("^b_|^bsp_", variables(fit1), value = TRUE)

  # Extract posterior draws
  draws <- as_draws_df(fit1)

  # Calculate probabilities and 94% HDI for each fixed effect
  results <- map_df(fixed_effect_vars, ~ {
    samples  <- draws[[.x]]
    var_name <- str_remove(.x, "^b_|^bsp_")
    hdi_vals <- compute_hdi_94(samples)
    data.frame(
      var          = var_name,
      prob_below_0 = mean(samples < 0),
      prob_above_0 = mean(samples > 0),
      hdi_lower_94 = hdi_vals[["lower"]],
      hdi_upper_94 = hdi_vals[["upper"]]
    )
  })

  # Merge with result_df
  result_df <- left_join(result_df, results, by = "var")

  # Save results — unless the convergence gate blocked them.
  if (convergence_gate$pass) {
    print("here comes your results!")
    write.csv(result_df, file.path(base_dir, summary_dir, paste0(dv,'.csv')), row.names = FALSE)
  } else {
    print(paste0("[convergence gate] WITHHELD: ",
                 file.path(base_dir, summary_dir, paste0(dv, ".csv"))))
  }

  ### Do a posterior predictive check!
  # All three pp_check calls are wrapped in tryCatch: hurdle_negbinom_huvary can produce
  # NAs in posterior predictions when shape → 0, crashing pp_check. On failure, any stale
  # image from a prior run is deleted so the absence of a file clearly signals the failure.
  print("aaaand PP check...")
  tryCatch({
    posterior_predictive_check <- pp_check(fit1)
    ggsave(file.path(base_dir, pp_dir, paste0(dv,"_posterior_check_plot.png")),
           plot = posterior_predictive_check, width = 10, height = 8, dpi = 800)
  }, error = function(e) {
    print(paste0("WARNING: pp_check (dens_overlay) failed — ", e$message))
    f <- file.path(base_dir, pp_dir, paste0(dv, "_posterior_check_plot.png"))
    if (file.exists(f)) { file.remove(f); print(paste0("  Deleted stale image: ", f)) }
  })

  ##### Almost done!!! Lets calculate some overall model comparison metrics and diagnostics:
  print("OK lets calculate model comparison metrics and diagnostics... ")

  # Initialize diagnostics list
  diagnostics_list <- list()
  diagnostics_list$dv <- dv
  diagnostics_list$model <- settings
  diagnostics_list$covariates <- covs
  diagnostics_list$N <- nobs(fit1)
  diagnostics_list$spvar <- spvar  # "" for covariate-only analyses

  # Create DHARMa residuals object once (we'll use it for multiple tests).
  # integer = TRUE is required for count/binary families so DHARMa applies the
  # correct randomized quantile residual computation. The default (FALSE) treats
  # the response as continuous, producing incorrect QQ plots and p-values for
  # hurdle_negbinom_huvary (caps_vision) and bernoulli (hppd_binary).
  integer_response <- settings %in% c("hurdle_negbinom_huvary", "bernoulli", "logistic")
  print(paste0("DHARMa integer flag: ", integer_response,
               "  (family settings = '", settings, "')"))
  print("Creating DHARMa residuals object...")
  sim_residuals <- NULL
  tryCatch({
    sim_residuals <- dh_check_brms(fit1, integer = integer_response)
    print("DHARMa residuals object created successfully")
  }, error = function(e) {
    print(paste0("Failed to create DHARMa residuals: ", e$message))
  })

  # ── DHARMa heteroscedasticity ────────────────────────────────────────────────
  # With spvar: test against the focal predictor (original behavior).
  # Without spvar: test against each covariate in the model.
  print("Checking heteroscedasticity with DHARMa...")
  if (nchar(spvar) > 0) {
    if (!is.null(sim_residuals)) {
      # Generate spvar vs. residuals plot (visual only — plotResiduals rank-transforms
      # the predictor internally before fitting the quantile regression lines).
      tryCatch({
        png(file.path(base_dir, diagnostic_dir, paste0(dv,"_heteroscedasticity_check.png")),
            width = 10, height = 8, units = "in", res = 800)
        plotResiduals(sim_residuals, fit1$data[[spvar]])
        dev.off()
      }, error = function(e) {
        if (dev.cur() > 1) dev.off()
        print(paste0("DHARMa heteroscedasticity plot failed: ", e$message))
        f <- file.path(base_dir, diagnostic_dir, paste0(dv, "_heteroscedasticity_check.png"))
        if (file.exists(f)) { file.remove(f); print(paste0("  Deleted stale image: ", f)) }
      })
      # Extract per-quantile p-values via testQuantiles() directly with rank-transformed
      # spvar. plotResiduals() rank-transforms internally before calling testQuantiles,
      # so manually replicating that here ensures the CSV p-values match what the figure
      # shows. Same approach as process_and_save_mediation_model_function.R lines 243–246.
      tryCatch({
        spvar_rk <- rank(fit1$data[[spvar]], ties.method = "average") /
                    length(fit1$data[[spvar]])
        hetero_test <- testQuantiles(sim_residuals, predictor = spvar_rk, plot = FALSE)
        # Combined BH-adjusted p + per-quantile (q25/q50/q75) individual pvals.
        # DHARMa colors a quantile line RED when its individual p < 0.05, even if
        # the combined BH-adjusted p is > 0.05. Saving all three makes the CSV
        # reflect exactly what the plot flags visually.
        diagnostics_list$dharma_heteroscedasticity_pval      <- hetero_test$p.value
        diagnostics_list$dharma_heteroscedasticity_q25_pval  <- if (!is.null(hetero_test$pvals)) hetero_test$pvals[1] else NA_real_
        diagnostics_list$dharma_heteroscedasticity_q50_pval  <- if (!is.null(hetero_test$pvals)) hetero_test$pvals[2] else NA_real_
        diagnostics_list$dharma_heteroscedasticity_q75_pval  <- if (!is.null(hetero_test$pvals)) hetero_test$pvals[3] else NA_real_
        print(paste0("DHARMa heteroscedasticity: combined p=", round(hetero_test$p.value, 4),
                     "  q25=", round(diagnostics_list$dharma_heteroscedasticity_q25_pval, 4),
                     "  q50=", round(diagnostics_list$dharma_heteroscedasticity_q50_pval, 4),
                     "  q75=", round(diagnostics_list$dharma_heteroscedasticity_q75_pval, 4)))
        if (any(c(hetero_test$p.value, hetero_test$pvals) < 0.05, na.rm = TRUE)) {
          print("WARNING: Potential heteroscedasticity (combined or per-quantile p < 0.05)!")
        }
      }, error = function(e) {
        print(paste0("DHARMa heteroscedasticity test failed: ", e$message))
        diagnostics_list$dharma_heteroscedasticity_pval     <- NA
        diagnostics_list$dharma_heteroscedasticity_q25_pval <- NA
        diagnostics_list$dharma_heteroscedasticity_q50_pval <- NA
        diagnostics_list$dharma_heteroscedasticity_q75_pval <- NA
      })
    } else {
      diagnostics_list$dharma_heteroscedasticity_pval     <- NA
      diagnostics_list$dharma_heteroscedasticity_q25_pval <- NA
      diagnostics_list$dharma_heteroscedasticity_q50_pval <- NA
      diagnostics_list$dharma_heteroscedasticity_q75_pval <- NA
    }
  } else {
    # Per-covariate heteroscedasticity
    print("  Running per-covariate DHARMa heteroscedasticity tests...")
    for (cov in all_covariates) {
      col_nm <- paste0("dharma_hetero_pval_", cov)
      if (!is.null(sim_residuals)) {
        cov_data <- fit1$data[[cov]]
        if (!is.null(cov_data)) {
          # Generate covariate vs. residuals plot (visual only).
          tryCatch({
            png(file.path(base_dir, diagnostic_dir,
                          paste0(dv, "_", cov, "_heteroscedasticity.png")),
                width = 10, height = 8, units = "in", res = 800)
            plotResiduals(sim_residuals, cov_data)
            dev.off()
          }, error = function(e) {
            if (dev.cur() > 1) dev.off()
            print(paste0("  DHARMa hetero plot for ", cov, " failed: ", e$message))
            f <- file.path(base_dir, diagnostic_dir, paste0(dv, "_", cov, "_heteroscedasticity.png"))
            if (file.exists(f)) { file.remove(f); print(paste0("  Deleted stale image: ", f)) }
          })
          # Extract per-quantile p-values via testQuantiles() with rank-transformed covariate.
          tryCatch({
            cov_rk <- rank(cov_data, ties.method = "average") / length(cov_data)
            hetero_test <- testQuantiles(sim_residuals, predictor = cov_rk, plot = FALSE)
            diagnostics_list[[col_nm]] <- hetero_test$p.value
            diagnostics_list[[paste0("dharma_hetero_q25_pval_", cov)]] <- if (!is.null(hetero_test$pvals)) hetero_test$pvals[1] else NA_real_
            diagnostics_list[[paste0("dharma_hetero_q50_pval_", cov)]] <- if (!is.null(hetero_test$pvals)) hetero_test$pvals[2] else NA_real_
            diagnostics_list[[paste0("dharma_hetero_q75_pval_", cov)]] <- if (!is.null(hetero_test$pvals)) hetero_test$pvals[3] else NA_real_
            print(paste0("  DHARMa hetero (", cov, "): combined p=", round(hetero_test$p.value, 4),
                         "  q25=", round(diagnostics_list[[paste0("dharma_hetero_q25_pval_", cov)]], 4)))
            if (any(c(hetero_test$p.value, hetero_test$pvals) < 0.05, na.rm = TRUE)) {
              print(paste0("  WARNING: Potential heteroscedasticity for ", cov, " (combined or per-quantile p < 0.05)!"))
            }
          }, error = function(e) {
            print(paste0("  DHARMa test for ", cov, " failed: ", e$message))
            diagnostics_list[[col_nm]]                                   <- NA
            diagnostics_list[[paste0("dharma_hetero_q25_pval_", cov)]]  <- NA
            diagnostics_list[[paste0("dharma_hetero_q50_pval_", cov)]]  <- NA
            diagnostics_list[[paste0("dharma_hetero_q75_pval_", cov)]]  <- NA
          })
        } else {
          print(paste0("  Covariate ", cov, " not found in fit1$data — skipping"))
          diagnostics_list[[col_nm]]                                   <- NA
          diagnostics_list[[paste0("dharma_hetero_q25_pval_", cov)]]  <- NA
          diagnostics_list[[paste0("dharma_hetero_q50_pval_", cov)]]  <- NA
          diagnostics_list[[paste0("dharma_hetero_q75_pval_", cov)]]  <- NA
        }
      } else {
        diagnostics_list[[col_nm]]                                   <- NA
        diagnostics_list[[paste0("dharma_hetero_q25_pval_", cov)]]  <- NA
        diagnostics_list[[paste0("dharma_hetero_q50_pval_", cov)]]  <- NA
        diagnostics_list[[paste0("dharma_hetero_q75_pval_", cov)]]  <- NA
      }
    }
  }

  # ── Posterior correlations ───────────────────────────────────────────────────
  # With spvar: flag coefficients with |r| > 0.7 against spvar posterior (original).
  # Without spvar: all pairwise correlations among fixed effects; flag |r| > 0.7 pairs.
  print("Computing posterior correlations with fixed effects...")
  tryCatch({
    draws <- as_draws_df(fit1)
    # Include both regular (b_) and monotonic (bsp_) population-level parameters.
    fixed_names <- grep("^b_|^bsp_", variables(fit1), value = TRUE)

    if (nchar(spvar) > 0) {
      # Original behavior: correlations of spvar with each other coefficient
      spvar_name <- paste0("b_", spvar)
      if (spvar_name %in% fixed_names) {
        other_vars <- setdiff(fixed_names, spvar_name)
        correlated_vars <- c()
        for (var in other_vars) {
          r <- cor(draws[[spvar_name]], draws[[var]], use = "complete.obs")
          if (!is.na(r) && abs(r) > 0.7) {
            var_clean <- gsub("^b_|^bsp_", "", var)
            correlated_vars <- c(correlated_vars, paste0(var_clean, "(", round(r, 2), ")"))
          }
        }
        diagnostics_list$correlated_variables <- if (length(correlated_vars) > 0)
          paste(correlated_vars, collapse = "; ") else ""
      } else {
        diagnostics_list$correlated_variables <- NA
      }

    } else {
      # Pairwise: all pairs of fixed effects posterior draws
      if (length(fixed_names) > 1) {
        correlated_pairs <- c()
        for (i in 1:(length(fixed_names) - 1)) {
          for (j in (i + 1):length(fixed_names)) {
            r <- cor(draws[[fixed_names[i]]], draws[[fixed_names[j]]], use = "complete.obs")
            if (!is.na(r) && abs(r) > 0.7) {
              v1 <- gsub("^b_|^bsp_", "", fixed_names[i])
              v2 <- gsub("^b_|^bsp_", "", fixed_names[j])
              correlated_pairs <- c(correlated_pairs,
                                    paste0(v1, "<->", v2, "(", round(r, 2), ")"))
            }
          }
        }
        diagnostics_list$correlated_pairs <- if (length(correlated_pairs) > 0)
          paste(correlated_pairs, collapse = "; ") else ""
      } else {
        diagnostics_list$correlated_pairs <- NA
      }
    }
  }, error = function(e) {
    print(paste0("Posterior correlations failed: ", e$message))
    if (nchar(spvar) > 0) {
      diagnostics_list$correlated_variables <- NA
    } else {
      diagnostics_list$correlated_pairs <- NA
    }
  })

  # Check distributional assumption with DHARMa
  print("Checking distributional assumption with DHARMa...")
  if (!is.null(sim_residuals)) {
    tryCatch({
      # Create and save comprehensive DHARMa diagnostic plot
      png(file.path(base_dir, diagnostic_dir, paste0(dv,"_dharma_diagnostics.png")),
          width = 10, height = 8, units = "in", res = 800)
      residuals_results <- testResiduals(sim_residuals)
      dev.off()

      # Store test results
      diagnostics_list$dharma_uniformity_pval <- residuals_results$uniformity$p.value
      diagnostics_list$dharma_dispersion_pval <- residuals_results$dispersion$p.value
      diagnostics_list$dharma_outlier_pval <- residuals_results$outliers$p.value

      # KS test (Kolmogorov-Smirnov) - extract from uniformity test
      diagnostics_list$ks_test_pval <- residuals_results$uniformity$p.value
      diagnostics_list$ks_test_statistic <- residuals_results$uniformity$statistic

      print(paste0("DHARMa uniformity test p-value: ", round(residuals_results$uniformity$p.value, 3)))
      print(paste0("DHARMa dispersion test p-value: ", round(residuals_results$dispersion$p.value, 3)))
      print(paste0("KS test p-value: ", round(residuals_results$uniformity$p.value, 3)))

      if (residuals_results$uniformity$p.value < 0.05) {
        print("WARNING: Residuals deviate from expected distribution (uniformity test p < 0.05)!")
      }
      if (residuals_results$dispersion$p.value < 0.05) {
        print("WARNING: Potential over/under-dispersion detected (p < 0.05)!")
      }

    }, error = function(e) {
      print(paste0("DHARMa diagnostics failed: ", e$message))
      diagnostics_list$dharma_uniformity_pval <- NA
      diagnostics_list$dharma_dispersion_pval <- NA
      diagnostics_list$dharma_outlier_pval <- NA
      diagnostics_list$ks_test_pval <- NA
      diagnostics_list$ks_test_statistic <- NA
    })
  } else {
    diagnostics_list$dharma_uniformity_pval <- NA
    diagnostics_list$dharma_dispersion_pval <- NA
    diagnostics_list$dharma_outlier_pval <- NA
    diagnostics_list$ks_test_pval <- NA
    diagnostics_list$ks_test_statistic <- NA
  }

  # testQuantiles against fitted values (global quantile fit test, no predictor)
  print("Running testQuantiles (vs fitted values) with DHARMa...")
  if (!is.null(sim_residuals)) {
    tryCatch({
      # plotResiduals() rank-transforms fitted values before the quantile test;
      # direct testQuantiles() does not. Use plotResiduals for consistency.
      png(file.path(base_dir, diagnostic_dir, paste0(dv,"_quantiles_check.png")),
          width = 10, height = 8, units = "in", res = 800)
      quantiles_test <- plotResiduals(sim_residuals)
      dev.off()
      diagnostics_list$dharma_quantiles_pval      <- quantiles_test$p.value
      diagnostics_list$dharma_quantiles_q25_pval  <- if (!is.null(quantiles_test$pvals)) quantiles_test$pvals[1] else NA_real_
      diagnostics_list$dharma_quantiles_q50_pval  <- if (!is.null(quantiles_test$pvals)) quantiles_test$pvals[2] else NA_real_
      diagnostics_list$dharma_quantiles_q75_pval  <- if (!is.null(quantiles_test$pvals)) quantiles_test$pvals[3] else NA_real_
      print(paste0("DHARMa quantiles: combined p=", round(quantiles_test$p.value, 4),
                   "  q25=", round(diagnostics_list$dharma_quantiles_q25_pval, 4),
                   "  q50=", round(diagnostics_list$dharma_quantiles_q50_pval, 4),
                   "  q75=", round(diagnostics_list$dharma_quantiles_q75_pval, 4)))
      if (any(c(quantiles_test$p.value, quantiles_test$pvals) < 0.05, na.rm = TRUE)) {
        print("WARNING: Significant quantile deviation (combined or per-quantile p < 0.05)!")
      }
    }, error = function(e) {
      print(paste0("DHARMa testQuantiles failed: ", e$message))
      diagnostics_list$dharma_quantiles_pval     <- NA
      diagnostics_list$dharma_quantiles_q25_pval <- NA
      diagnostics_list$dharma_quantiles_q50_pval <- NA
      diagnostics_list$dharma_quantiles_q75_pval <- NA
    })
  } else {
    diagnostics_list$dharma_quantiles_pval     <- NA
    diagnostics_list$dharma_quantiles_q25_pval <- NA
    diagnostics_list$dharma_quantiles_q50_pval <- NA
    diagnostics_list$dharma_quantiles_q75_pval <- NA
  }

  # Create diagnostics dataframe from whatever succeeded
  print("Creating diagnostics dataframe...")
  diagnostics_df <- as.data.frame(diagnostics_list, stringsAsFactors = FALSE)

  # Save diagnostics separately
  write.csv(diagnostics_df,
            file = file.path(base_dir, diagnostic_dir, paste0(dv,'_diagnostics.csv')),
            row.names = FALSE)
  print(paste0("Diagnostics saved for ", dv))
  print(paste0("Diagnostics columns: ", paste(names(diagnostics_df), collapse = ", ")))

  #############################################################################
  #############################################################################
  ##### AVERAGE PREDICTIVE COMPARISON (APC)                               #####
  #############################################################################
  #
  # The estimand, the derivation, and the reason it is computed with
  # posterior_epred() rather than by hand are all documented on
  # average_predictive_comparison() near the top of this file.  Only the parts
  # specific to WRITING THE RESULT are repeated here.
  #
  # WHAT IS CONTRASTED
  #   x_0 = 0.0   the reference level.  0 is the MEAN of spvar, because Gelman
  #               normalisation centres the variable.
  #   x_1 = 0.5   Gelman divides by 2 SD, so the normalised variable has SD 0.5.
  #               0.5 units is therefore simultaneously "+1 raw SD" and "+1 SD of
  #               the normalised variable" -- both readings give the same number.
  #
  # WHAT COMES OUT
  #   The S values of delta are summarised into a single row:
  #     mean          the REPORTED point estimate as of 2026-08-23 -- the same
  #                   summary of the posterior as the `Estimate` column in this
  #                   script's coefficient tables, so both halves of a results row
  #                   summarise the posterior the same way.  See POINT_ESTIMATE_COL
  #                   in modules/master_config.py.
  #     median        retained so the choice of point estimate can be revisited
  #                   without refitting.  NOT the reported value.
  #     94% HDI       narrowest interval containing 94% of the S values.  The
  #                   94% rather than 95% is the project-wide convention.
  #     prob_above_0  proportion of the S deltas above 0 (and below, likewise).
  #                   Posterior probabilities, NOT p-values: neither can be read
  #                   as a false-positive rate.
  #     scale         what delta is denominated in; differs by family and is
  #                   written verbatim into the CSV's `scale` column.
  #
  # ON THE FILENAME.  "counterfactual" is a misnomer, retained only because it is
  # baked into output filenames, CSV column names, and compile_nonsp_results.py.
  # Renaming it would silently break the compiler.  What is computed is an
  # average predictive comparison.
  #
  # OUTPUT
  #   {base_dir}/summary_dfs/{dv}_counterfactual.csv  (one row)
  #   Columns: dv, settings, spvar, X0, X1, contrast_label, scale,
  #            median, mean, hdi_lower_94, hdi_upper_94, prob_above_0,
  #            prob_below_0, N_obs, N_draws
  #############################################################################

  ## CF_SCALE_BY_FAMILY: the `scale` column's value, per family.  This is a label
  ## only -- it documents the units delta is denominated in and is consumed
  ## downstream by compile_nonsp_results.py.  An unlisted family is a hard stop
  ## rather than a blank label, so a new family cannot reach the CSV unlabelled.
  CF_SCALE_BY_FAMILY <- c(
    hurdle_negbinom_huvary = "response_count",     # delta is in COUNTS of dv
    bernoulli              = "probability",        # delta is a RISK DIFFERENCE
    logistic               = "probability",
    student_t              = "response_scale",
    gamma                  = "response_exp_scale",
    zero_inflated_beta     = "proportion_scale",
    beta                   = "proportion_scale"
  )

  ## Guard: an APC needs a focal predictor to move. Covariate-only runs skip it.
  ## The convergence gate is the second guard: an unconverged posterior gives an
  ## unreportable contrast, so it is not computed rather than computed and binned.
  if (nchar(spvar) > 0 && !convergence_gate$pass) {
    print(paste0("[convergence gate] WITHHELD: ",
                 file.path(base_dir, summary_dir, paste0(dv, "_counterfactual.csv"))))
  } else if (nchar(spvar) > 0) {
    print("Running counterfactual analysis (E[Y|X1] - E[Y|X0])...")

    ## The two focal-predictor values being contrasted, in Gelman-normalised units.
    CF_X0 <- 0.0
    CF_X1 <- 0.5

    tryCatch({

      if (!settings %in% names(CF_SCALE_BY_FAMILY)) {
        stop(paste0("Counterfactual: unsupported family '", settings, "'"))
      }
      ## cf_scale: units of delta, recorded in the CSV
      cf_scale <- unname(CF_SCALE_BY_FAMILY[[settings]])

      ## delta_s: length S - the population-average contrast, one per draw.
      ## Every family's mean function, every covariate type (continuous, factor,
      ## monotonic mo()) and both submodels of a hurdle are handled inside
      ## posterior_epred(); see average_predictive_comparison() above.
      delta_s <- average_predictive_comparison(fit1, spvar, CF_X0, CF_X1)

      ## S_cf / N_cf: draws, and subjects retained in the fit (post complete.cases)
      S_cf <- length(delta_s)
      N_cf <- nrow(fit1$data)

      ## hdi_cf: named c(lower, upper) - errors on any non-finite draw
      hdi_cf <- compute_hdi_94(delta_s)

      ## cf_df: exactly one row; schema is consumed by compile_nonsp_results.py
      cf_df  <- data.frame(
        dv             = dv,
        settings       = settings,
        spvar          = spvar,
        X0             = CF_X0,
        X1             = CF_X1,
        contrast_label = paste0(spvar, ": X0=", CF_X0, " -> X1=", CF_X1,
                                " Gelman units (+1 raw SD)"),
        scale          = cf_scale,
        median         = median(delta_s),
        mean           = mean(delta_s),
        hdi_lower_94   = hdi_cf[["lower"]],
        hdi_upper_94   = hdi_cf[["upper"]],
        ## prob_above_0 / prob_below_0 are raw posterior proportions, NOT p-values
        prob_above_0   = mean(delta_s > 0),
        prob_below_0   = mean(delta_s < 0),
        N_obs          = N_cf,
        N_draws        = S_cf,
        stringsAsFactors = FALSE
      )

      cf_path <- file.path(base_dir, summary_dir, paste0(dv, "_counterfactual.csv"))
      write.csv(cf_df, cf_path, row.names = FALSE)
      print(paste0("Counterfactual saved: ", cf_path))
      ## Reported point estimate is the mean (POINT_ESTIMATE_COL in
      ## modules/master_config.py); cf_df still carries both columns.
      print(paste0("  mean delta = ", round(mean(delta_s), 5),
                   "  |  94% HDI [", round(hdi_cf[["lower"]], 5), ", ",
                   round(hdi_cf[["upper"]], 5), "]",
                   "  |  P(>0) = ", round(mean(delta_s > 0), 3)))

    }, error = function(e) {
      # A compute_hdi_94() failure means the posterior itself is bad. Re-raise it so
      # the job fails, instead of logging and exiting 0 with no output written.
      if (inherits(e, HDI_ERROR_CLASS)) stop(e)
      print(paste0("Counterfactual analysis failed: ", e$message))
    })
  }

  return(result_df)
}

