# ── A note on the word "counterfactual" ──────────────────────────────────────
# "counterfactual" appears throughout this file's output filenames
# ({dv}_counterfactual.csv) and CSV column names. It is a misnomer: what is
# computed is an average predictive comparison, not a causal counterfactual. The
# name is retained because compile_nonsp_results.py reads those filenames and
