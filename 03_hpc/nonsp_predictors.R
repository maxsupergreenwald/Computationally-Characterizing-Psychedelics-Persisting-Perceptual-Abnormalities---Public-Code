# "nooutlier" is refused rather than silently ignored.  It dropped rows with |spvar| > 1 in
# Gelman-normalized space (= +-2 raw SD).  That threshold is only meaningful
# against a fixed normalization sample, and there is no longer one at filter
# time: the CSV ships raw and normalization runs after subsetting.  Rather than
# silently redefine which rows it drops, the keyword is refused.  Use "iqr",
# whose 1.5xIQR fence is quantile-based and therefore identical on any positive
# affine rescaling of the column.  Removed from R_SIDE_SUFFIXES in
# master_config.py too, so generation fails first; this stop() is the backstop
# for a stale job file already staged on the cluster.
if (grepl("nooutlier", model_type_str, ignore.case = FALSE)) {
  stop(paste0(
    "  [nooutlier] This keyword is not supported and filters ",
    "anything. It thresholded |spvar| on the Gelman-normalized scale, which has ",
    "no fixed meaning now that normalization happens in R after subsetting. ",
    "Model type requested: '", model_type_str, "'. ",
    "Use 'iqr' instead, or regenerate the job file with generate_hpc_jobs.py."))
}

# The iqr filter requires a focal predictor — skip when spvar is empty.
# spvar arrives as its {x}_normalized name, but that column does not exist yet
# (normalization is below), so resolve to the raw column.  The 1.5xIQR fence is
# quantile-based, so it selects exactly the same rows on either scale.
if (grepl("iqr", model_type_str, ignore.case = FALSE)) {
  spvar_col <- args[6]
  if (nchar(spvar_col) > 0) {
    spvar_col <- resolve_raw_column(df_new, spvar_col)
    n_before  <- nrow(df_new)
    x <- df_new[[spvar_col]]

    if (all(is.na(x))) {
      print(paste0("  [iqr] All values missing for spvar=", spvar_col,
                   "; skipping IQR filter."))
    } else {
      q1 <- as.numeric(stats::quantile(x, probs = 0.25, na.rm = TRUE))
      q3 <- as.numeric(stats::quantile(x, probs = 0.75, na.rm = TRUE))
      iqr_val <- q3 - q1
      lower <- q1 - 1.5 * iqr_val
      upper <- q3 + 1.5 * iqr_val

      df_new <- df_new[!is.na(df_new[[spvar_col]]) &
                       df_new[[spvar_col]] >= lower &
                       df_new[[spvar_col]] <= upper, ]

      print(paste0("  [iqr] IQR exclusion applied (spvar=", spvar_col,
                   ", Q1=", round(q1, 4), ", Q3=", round(q3, 4),
                   ", IQR=", round(iqr_val, 4),
                   ", bounds=[", round(lower, 4), ", ", round(upper, 4), "]): ",
                   nrow(df_new), " rows (removed ", n_before - nrow(df_new), ")"))
    }
  } else {
    print("  [iqr] spvar is empty — IQR filter requires a focal predictor; skipping.")
  }
}

