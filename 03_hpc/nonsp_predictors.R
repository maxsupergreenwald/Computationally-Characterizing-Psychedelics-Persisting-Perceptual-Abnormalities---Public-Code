# -----------------------------------------------------------------------
# Complete cases, then normalization.  ORDER IS THE POINT OF THIS BLOCK.
#
# brms drops incomplete cases itself, but only once brm() is called — which is
# after this script would have normalized.  Dropping them here instead makes the
# normalization sample and the estimation sample the same set of rows, so every
# _normalized column is at mean 0 / sd 0.5 on exactly the rows that enter the
# likelihood.  That is what "+1 raw SD" in the counterfactual output means, and
# before 2026-08-22 it silently meant +1 SD of a larger sample.
#
# Model variables = the DV (args[3]) plus every term on the formula RHS
# (args[5], which already contains the focal predictor as well as the
# covariates).  model_formula_vars() unwraps mo() and splits interactions.
# -----------------------------------------------------------------------
model_vars <- c(args[3], model_formula_vars(args[5]))
