# Empty string -> NA for CHARACTER factor covariates.  Added 2026-08-31.
#
# read.csv()'s default na.strings is "NA" only, so a blank field in a
# *character* column arrives as "" rather than NA.  For a factor covariate that
# is silently wrong in three compounding ways: the missing group survives
# drop_incomplete_model_rows() (which tests for NA), as.factor() turns "" into a
