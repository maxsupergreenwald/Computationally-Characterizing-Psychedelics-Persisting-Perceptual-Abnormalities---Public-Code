def find_most_recent_csv(directory, prefix,
                          exclude=("LABELS", "withstates", "byblock",
                                   "bad_rhat", "good_rhat")):
    """Return path of most-recently-modified CSV in *directory* starting with
    *prefix*, ignoring filenames containing any string in *exclude*."""
    if not os.path.isdir(directory):
        return None
    candidates = [
        os.path.join(directory, f)
        for f in os.listdir(directory)
        if (f.endswith(".csv")
            and f.startswith(prefix)
            and not any(ex in f for ex in exclude))
    ]
    if not candidates:
        return None
    return max(candidates, key=os.path.getmtime)


def compile_hgf_csvs(results_dir, suffix):
    """Concatenate all per-subject CSVs ending in *suffix*.csv from
    *results_dir*. Returns a DataFrame with record_id as int, or an empty
    DataFrame when no matching files are found."""
    if not os.path.isdir(results_dir):
        return pd.DataFrame()
    csv_files = [f for f in os.listdir(results_dir)
                 if f.endswith(f"{suffix}.csv")]
    if not csv_files:
        return pd.DataFrame()
    dfs = []
    for fname in csv_files:
        try:
            dfs.append(pd.read_csv(os.path.join(results_dir, fname)))
        except Exception as exc:
            print(f"    Warning: could not read {fname}: {exc}")
    if not dfs:
        return pd.DataFrame()
    fulldf = pd.concat(dfs, ignore_index=True)
    # Normalise record_id column
    for col in ("subj_id", "ID", "record_id"):
        if col in fulldf.columns:
            fulldf["record_id"] = fulldf[col].astype(int)
            if col != "record_id":
                fulldf = fulldf.drop(columns=[col])
            break
    return fulldf


def validate_pwpe_sign(long_df, task):
    """Sanity-check pwPE sign correspondence.

    After shifting pwPE by -1, trial t's pwPE was produced by the HGF
    updating on trial t's response.  We expect:
      response=1  → pwPE tends to be positive
      response=0  → pwPE tends to be negative

    Prints a short report; does not raise on failure (violations indicate
    a mis-alignment that warrants investigation, not a crash).
    """
    ref_col = "response"
    print(f"\n  --- pwPE sign validation ({task}) ---")
    if ref_col not in long_df.columns:
        # Fallback: some long dfs prefix the column with the task name (e.g. vch_response)
        fallback = f"{task}_{ref_col}"
        if fallback in long_df.columns:
            ref_col = fallback
        else:
            print(f"  Skipped: neither '{ref_col}' nor '{fallback}' found in long df")
            return
    if "pwPE" not in long_df.columns:
        print(f"  Skipped: 'pwPE' not yet in long df")
        return

    valid = long_df.dropna(subset=[ref_col, "pwPE"])
    if valid.empty:
        print(f"  Skipped: no rows with both '{ref_col}' and 'pwPE' non-NaN")
        return

    for val, label in [(1, "1 (expect +pwPE)"), (0, "0 (expect -pwPE)")]:
        sub = valid.loc[valid[ref_col] == val, "pwPE"]
        n   = len(sub)
        if n == 0:
            print(f"    {ref_col}={val}: no data")
            continue
        pct_pos = (sub > 0).sum() / n * 100
        med     = sub.median()
        flag    = ""
        if val == 1 and pct_pos < 60:
            flag = " ← WARNING: fewer than 60% positive"
        if val == 0 and pct_pos > 40:
            flag = " ← WARNING: more than 40% positive"
        print(f"    {ref_col}={label}: n={n}, "
              f"median={med:.4f}, "
              f"{pct_pos:.1f}% positive{flag}")


