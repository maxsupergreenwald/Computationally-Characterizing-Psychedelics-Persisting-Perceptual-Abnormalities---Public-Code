def _scale_time(hhmm: str, factor: float) -> str:
    """Scale a HH:MM wall-time string by factor and return HH:MM."""
    h, m   = int(hhmm.split(":")[0]), int(hhmm.split(":")[1])
    total  = int((h * 60 + m) * factor)
    return f"{total // 60}:{total % 60:02d}"

_CATCHUP_FACTOR   = 1.5
_DEFAULT_N_ITER   = 1000
_n_iter_catchup   = int(_DEFAULT_N_ITER * _CATCHUP_FACTOR)   # 1500
_HPC_SPEC_DIR     = f"{HPC_JULIA_CH_DIR}/data_n_cmnds/array_scripts"
_LOCAL_SPEC_DIR   = os.path.join(LOCAL_JULIA_CH_DIR, "data_n_cmnds", "array_scripts")
os.makedirs(_LOCAL_SPEC_DIR, exist_ok=True)

# Collect never-ran subjects alongside the already-tracked bad-rhat ones
