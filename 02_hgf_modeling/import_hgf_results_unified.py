# ─── CATCH-UP JOB GENERATION ──────────────────────────────────────────────────
# Detects two failure modes per task/timepoint:
#   bad_rhat   — subject ran but ≥1 rhat was outside 0.9–1.1 (caught above)
#   never_ran  — staging CSV exists locally but no _medians.csv was pulled from HPC
# Generates a catch-up job array with 1.5× n_iterations and 1.5× wall time.
# File indices are resolved from the local staging directory — no SSH needed.
