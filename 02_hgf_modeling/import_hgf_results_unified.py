for task in ACTIVE_TASKS:

    timepoints = cfg["timepoints_vch"]

    for tp in timepoints:
        print(f"\n{'='*80}")
        print(f"  Task={task.upper()}  |  Timepoint={tp}  |  Model={MODEL_TYPE}")
        print(f"{'='*80}")

        # Results dir: where per-subject CSVs landed after scp pull.
        # scp -r .../vch/ local_hppd/  creates local_hppd/vch/{files}, so
        # the actual path is results_local[task]/MODEL_TYPE/tp/task/
        results_dir = os.path.join(
            cfg["results_local"][task], MODEL_TYPE, tp, task
        )

        # ── Load per-subject result CSVs ───────────────────────────────────────
        # Files are named  {subj_id}state_trajectories.csv  (no leading underscore)
        #                  {subj_id}_medians.csv
        #                  {subj_id}_rhats.csv
        states  = compile_hgf_csvs(results_dir, "state_trajectories")
        medians = compile_hgf_csvs(results_dir, "_medians")
        rhats   = compile_hgf_csvs(results_dir, "_rhats")

        if states.empty:
            print(f"  WARNING: No state trajectory files found in:\n    {results_dir}")
            print(f"  Have you pulled HPC results? Skipping this task/timepoint.")
            continue

        print(f"  Found HGF results: {states['record_id'].nunique()} participants, "
              f"{len(states)} state rows")

        # ── Rename columns to analysis-friendly names ──────────────────────────
        states.rename(columns=STATE_NAMES, inplace=True)
        if not medians.empty:
            medians.rename(columns=PARAM_NAMES, inplace=True)
        if not rhats.empty:
            rhats.rename(columns=RHAT_PARAM_NAMES, inplace=True)

        if "modality" not in states.columns:
            states["modality"] = task

        # ── Rhat QC ────────────────────────────────────────────────────────────
        params_present = [p for p in ("beta", "nu", "omega", "omega3")
                          if not medians.empty and p in medians.columns]

        if not rhats.empty:
            all_bad_ids_this_run = set()
            for param in params_present:
                if param not in rhats.columns:
                    continue
                bad_ids = rhats.loc[
                    (rhats[param] > 1.1) | (rhats[param] < 0.9), "record_id"
                ].unique()
                if len(bad_ids) > 0:
                    print(f"  Rhat QC: {param} → NaN for {len(bad_ids)} participants "
                          f"(rhat outside 0.9–1.1): {sorted(bad_ids.tolist())}")
                    medians.loc[medians["record_id"].isin(bad_ids), param] = np.nan
                    all_bad_ids_this_run.update(bad_ids.tolist())
                    bad_rhat_by_param[(task, tp, MODEL_TYPE, param)] = sorted(
                        bad_ids.tolist())
                    rhats[rhats["record_id"].isin(bad_ids)].to_csv(
                        os.path.join(results_dir, f"bad_rhats_{param}.csv"),
                        index=False)
                    rhats[~rhats["record_id"].isin(bad_ids)].to_csv(
                        os.path.join(results_dir, f"good_rhats_{param}.csv"),
                        index=False)
                else:
                    rhats.to_csv(
                        os.path.join(results_dir, f"good_rhats_{param}.csv"),
                        index=False)
            if all_bad_ids_this_run:
                bad_rhat_subjects[(task, tp, MODEL_TYPE)] = sorted(all_bad_ids_this_run)

        # ── Warn about participants with task data but missing HGF results ─────
        wide_ids  = set(df["record_id"].unique())
        hgf_ids   = set(states["record_id"].unique())
        missing   = sorted(wide_ids - hgf_ids)
        if missing:
            print(f"\n  WARNING: {len(missing)} record_id(s) in wide df have no "
                  f"HGF results for {task}/{tp}:")
            print(f"  {missing}")

        # ── Trial numbering: 0-indexed → 1-indexed ────────────────────────────
        # Julia saves timestep = 0, 1, ..., N-1; convert to 1-based trials
        if "trial" in states.columns:
            states["trial"] = states["trial"].astype(int)
            if states["trial"].min() == 0:
                states["trial"] += 1
                print(f"  Converted 0-indexed trials to 1-indexed")

        # ── Block assignment ───────────────────────────────────────────────────
        states["block"] = ((states["trial"] - 1) // VCH_BLOCK_SIZE).astype(int) + 1

        # ── Compute pwPE ───────────────────────────────────────────────────────
        # pwPE = xbin_pe / xprob_pred_pp
        # (xbin_prediction_precision = 1 for all binary nodes, so it cancels)
        #
        # The -1 temporal alignment is applied HERE, at source, rather than after
        # the merge into the long df.  The HGF at trial t was updated by trial
        # t-1's response, so the raw PE runs one trial ahead of the response that
        # caused it; shifting by -1 puts trial t's pwPE alongside trial t's
        # response.
        #
        # Doing the shift on `states` — before it is either merged into the long
        # df or aggregated into the wide df — guarantees both consumers see the
        # SAME series. When the shift was applied only to the merged long df,
        # the per-block wide columns (vch_pwPE_block_1..12) were medians of the
        # UNSHIFTED series while the long df carried the shifted one, so the two
        # disagreed by up to ~0.4.  (vch_pwPE_median / _mean were unaffected: a
        # whole-series median or mean is invariant to a one-trial shift.)
        #
        # Order matters: clip first, then shift, so the NaNs introduced by
        # clipping travel with the values they belong to.
        if "xbin_pe" in states.columns and "xprob_pred_pp" in states.columns:
            states["pwPE"] = states["xbin_pe"] / states["xprob_pred_pp"]
            n_extreme = (states["pwPE"].abs() > 5).sum()
            if n_extreme > 0:
                print(f"  Clipping {n_extreme} extreme |pwPE| > 5 values → NaN")
            states.loc[states["pwPE"].abs() > 5, "pwPE"] = np.nan

            # Sort explicitly: the shift is only meaningful in trial order, and
            # `states` is a concatenation of per-subject files.
            states = states.sort_values(["record_id", "trial"]).reset_index(drop=True)
            states["pwPE"] = states.groupby("record_id")["pwPE"].shift(-1)

        # ── Columns to aggregate (exclude bookkeeping / merge-key cols) ────────
        skip_agg = {"record_id", "trial", "block", "modality", "ID", "timestep"}
        state_agg_cols = [c for c in states.columns if c not in skip_agg]

        # ══════════════════════════════════════════════════════════════════════
        # STEP 1: Merge states into long df → save _withstates CSV
        # ══════════════════════════════════════════════════════════════════════
        if DO_MERGE_STATES:

            # Locate the long df for this task/timepoint. Try the
            # modality-specific file first, then the combined ch_master.
            long_prefixes = [f"{task}_master_", "ch_master_"]
            long_path     = None
            for pfx in long_prefixes:
                long_path = find_most_recent_csv(long_df_dir, pfx)
                if long_path:
                    break

            if long_path is None:
                print(f"  WARNING: No long df found for {task}/{tp} in "
                      f"{long_df_dir}. Skipping state merge.")
            else:
                print(f"  Long df: {os.path.basename(long_path)}")
                long_df = pd.read_csv(long_path)
                long_df["record_id"] = long_df["record_id"].astype(int)

                # If combined ch_master, filter to current modality
                if "modality" in long_df.columns:
                    long_df = long_df[long_df["modality"] == task].copy()

                # Merge keys: always record_id + trial; add block if long df has it
                merge_keys = ["record_id", "trial"]
                if "block" in long_df.columns:
                    merge_keys.append("block")

                # Drop any pre-existing HGF state columns in long df to avoid conflicts
                overlap = [c for c in state_agg_cols if c in long_df.columns]
                if overlap:
                    print(f"  Dropping pre-existing HGF columns from long df: {overlap}")
                    long_df = long_df.drop(columns=overlap)

                states_to_merge = states.drop(columns=["modality"], errors="ignore")
                merged = long_df.merge(states_to_merge, on=merge_keys, how="left")

                if len(merged) != len(long_df):
                    print(f"  ERROR: Merge changed row count! "
                          f"Before={len(long_df)}, After={len(merged)}. "
                          f"Long df NOT saved.")
                else:
                    # NOTE: pwPE already carries the -1 alignment shift, applied
                    # to `states` above so that the long df and the wide per-block
                    # aggregates share one series.  Do not shift again here.

                    # Validate pwPE sign correspondence
                    validate_pwpe_sign(merged, task)

                    # Save withstates long df
                    date_str = datetime.today().strftime("%m-%d-%Y")
                    sfx      = model_suffix  # "" or "_3lev"
                    out_name = f"{task}_master_withstates{sfx}{variant_suffix}_{date_str}.csv"
                    out_path = os.path.join(long_df_dir, out_name)
                    merged.to_csv(out_path, index=False)
                    print(f"  Saved: {out_name}  ({len(merged)} rows)")

        # ══════════════════════════════════════════════════════════════════════
        # STEP 2: Parameters → wide df
        # ══════════════════════════════════════════════════════════════════════
        if DO_PARAMS_TO_WIDE and not medians.empty:
            med_wide = medians[["record_id"] + params_present].copy()
            rename_map = {p: f"{task}_{p}{model_suffix}" for p in params_present}
            med_wide.rename(columns=rename_map, inplace=True)
            med_wide["record_id"] = med_wide["record_id"].astype(int)

            new_cols = [c for c in med_wide.columns if c != "record_id"]
            # For columns that already exist: fill NaN only (don't overwrite populated values).
            # For genuinely new columns: add via left merge.
            existing = [c for c in new_cols if c in df.columns]
            truly_new = [c for c in new_cols if c not in df.columns]
            if existing:
                # Update NaN cells in-place using the new values
                tmp = med_wide[["record_id"] + existing].set_index("record_id")
                for col in existing:
                    df_idx = df.set_index("record_id")[col]
                    updated = df_idx.combine_first(tmp[col])
                    df[col] = df["record_id"].map(updated)
            if truly_new:
                df = df.merge(med_wide[["record_id"] + truly_new], on="record_id", how="left")
            wide_df_modified = True
            print(f"  Params → wide df: {new_cols}")

        # ══════════════════════════════════════════════════════════════════════
        # STEP 3: Per-subject state medians + means → wide df
        # ══════════════════════════════════════════════════════════════════════
        if DO_SUBJECT_MEDIANS:
            agg_src = states[["record_id"] + state_agg_cols].copy()

            subj_med  = agg_src.groupby("record_id").median().reset_index()
            subj_mean = agg_src.groupby("record_id").mean().reset_index()

            subj_med.rename(columns={
                c: f"{task}_{c}_median{model_suffix}" for c in state_agg_cols
            }, inplace=True)
            subj_mean.rename(columns={
                c: f"{task}_{c}_mean{model_suffix}" for c in state_agg_cols
            }, inplace=True)

            for src, label in [(subj_med, "medians"), (subj_mean, "means")]:
                src["record_id"] = src["record_id"].astype(int)
                new_cols = [c for c in src.columns if c != "record_id"]
                existing = [c for c in new_cols if c in df.columns]
                if existing:
                    df = df.drop(columns=existing)
                df = df.merge(src, on="record_id", how="left")
            wide_df_modified = True
            print(f"  Per-subject {len(state_agg_cols)} states "
                  f"× median+mean → wide df")

        # ══════════════════════════════════════════════════════════════════════
        # STEP 4: Per-block state medians → wide df
        # ══════════════════════════════════════════════════════════════════════
        if DO_BLOCK_MEDIANS:
            blocks  = sorted(states["block"].dropna().unique().astype(int))
            blk_dfs = []
            for blk in blocks:
                blk_data = states.loc[
                    states["block"] == blk, ["record_id"] + state_agg_cols
                ].copy()
                blk_med = blk_data.groupby("record_id").median().reset_index()
                blk_med.rename(columns={
                    c: f"{task}_{c}_block_{blk}{model_suffix}"
                    for c in state_agg_cols
                }, inplace=True)
                blk_dfs.append(blk_med)

            if blk_dfs:
                blk_wide = blk_dfs[0]
                for bdf in blk_dfs[1:]:
                    blk_wide = blk_wide.merge(bdf, on="record_id", how="outer")
                blk_wide["record_id"] = blk_wide["record_id"].astype(int)

                new_cols = [c for c in blk_wide.columns if c != "record_id"]
                existing = [c for c in new_cols if c in df.columns]
                if existing:
                    df = df.drop(columns=existing)
                df = df.merge(blk_wide, on="record_id", how="left")
                wide_df_modified = True
                print(f"  Per-block medians: {len(blocks)} blocks "
                      f"× {len(state_agg_cols)} states → wide df")


