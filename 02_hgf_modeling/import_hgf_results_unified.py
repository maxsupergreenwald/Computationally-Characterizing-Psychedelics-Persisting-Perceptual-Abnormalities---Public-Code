"""
import_hgf_results_unified.py — HGF Results Import and Merge (VCH task)
=========================================================================

Loads HGF model-fitting results pulled from HPC (generated by
model_fitting_singleagent_forarray.jl), merges them with the existing
long-format DataFrame, and copies summary variables into the project wide df.

Expected local result path after scp pull (from hgf_pipeline.py Step 4):
  cfg["results_local"]["vch"] / MODEL_TYPE / tp / vch / {record_id}.*

Output files per timepoint:
  - vch_master_withstates[_3lev][_nominal]_{date}.csv  (long df + HGF states)
  - df_withstates_{proj_suffix}[_nominal]_{date}.csv    (wide df snapshot)
  - wide df overwritten at long_df_dir/df_{proj_suffix}_*.csv with new cols

  The [_nominal] suffix appears when MODEL_TYPE = "2level_nominal" (shadow
  pipeline using raw condition proportions as stimulus strength).  Column names
  inside the dataframes are identical to the standard 2-level run — only the
  output filenames differ, so both variants can coexist in the same directory.

Interactive use: if 'df' already exists in the namespace (notebook), it is
used directly. Otherwise the most-recent df_{proj_suffix}_*.csv is loaded.
"""

################################################################################
# ─── ROLE IN THE MANUSCRIPT ───────────────────────────────────────────────────
#
# STAGE 3 OF 3 in the HGF pipeline — the step that turns per-subject Julia
# output into the analysis dataframes every downstream result depends on.
#
#     hgf_pipeline.py ──▶ model_fitting_singleagent_forarray.jl ──▶ THIS SCRIPT
#
# What it is responsible for
#     1. Collecting each participant's posterior medians and per-trial state
#        trajectories from the pulled HPC results.
#     2. Enforcing the convergence gate: any parameter whose R-hat falls outside
#        0.9–1.1 is set to NaN rather than silently carried into the analysis.
#     3. Deriving pwPE (precision-weighted prediction error) and realigning it in
#        time — the raw HGF output leads the response by one trial.
#     4. Writing the wide and long dataframes consumed by every statistical model
#        and figure in the manuscript.
#
# Outputs (into <repo>/data/final/)
#     df_withstates_public_<date>.csv  wide: one row per participant.  Supplies
#                                      vch_nu, vch_beta, vch_omega and the
#                                      per-subject / per-block state summaries.
#     vch_master_withstates_<date>.csv long: one row per trial per participant.
#
# Input safety
#     The input wide df is COPIED to data/final/backups/ before anything is
#     modified, named <stem>_backup_<MM-DD-YYYY_HHMMSS>.csv.  The wide df
#     already ships with HGF columns from a previous run; those columns are
#     dropped and re-derived from the freshly pulled results, so the backup is
#     the only record of the superseded values.
#
# Variant suffix — the subtlety most likely to bite
#     "_nominal"  output FILENAMES carry the suffix, but the COLUMN names are
#                 identical to the empiric run.  Nominal and empiric results
#                 therefore cannot coexist in one wide df; whichever was imported
#                 last is what vch_nu / vch_beta / vch_omega currently hold.
#
# Catch-up jobs
#     At the end of a run the script reports two distinct failure modes — ran but
#     failed R-hat, versus never ran at all — and offers to emit a job array that
#     refits just those participants at 1.5× the iterations and wall time.
################################################################################

